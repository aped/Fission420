#!/usr/bin/env python3
"""Write THIRD_PARTY_LICENSES.txt for the shipped binaries (rcad, rcad-cli).

Collects every third-party crate linked into them for one target (normal dependency edges
only, as resolved by `cargo metadata --filter-platform`), with its licence expression,
authors and repository. It then appends the licence texts the crates ship (LICENSE*,
COPYING*, the font licences in fonts/*.txt), de-duplicated. Crates that ship no licence file
are covered by the canonical texts appended at the end (Apache-2.0 from LICENSE-APACHE,
the MIT terms with the crate's authors as copyright holders).

Usage (from the repository root): tools/ci/third_party_licenses.py <target-triple> <out-file>
Standard library only, so it runs on every CI runner. See docs/CI.md.
"""
import hashlib
import json
import os
import re
import subprocess
import sys

ROOTS = ("rcad", "rcad-cli")
LICENSE_FILE = re.compile(r"(?i)^(licen[cs]e|copying|unlicense|ofl|ufl)|license.*\.txt$")


def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def runtime_packages(meta):
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    stack = [p["id"] for p in meta["packages"] if p["name"] in ROOTS]
    seen = set()
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    third = [pkgs[i] for i in seen if pkgs[i]["source"]]  # path crates are ours
    return sorted(third, key=lambda p: (p["name"], p["version"]))


def licence_files(pkg):
    root = os.path.dirname(pkg["manifest_path"])
    found = []
    for sub in ("", "fonts"):
        d = os.path.join(root, sub)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            # Every .txt next to bundled fonts is a font licence (OFL, UFL, Hack's terms).
            hit = LICENSE_FILE.search(f) or (sub == "fonts" and f.endswith(".txt"))
            if hit and os.path.isfile(os.path.join(d, f)):
                found.append(os.path.join(d, f))
    return found


def main():
    target, out = sys.argv[1], sys.argv[2]
    pkgs = runtime_packages(metadata(target))
    texts = {}  # sha -> (text, [crate ids])
    bare = []
    lines = [
        "Third-party software in the R-CAD binaries (rcad, rcad-cli)",
        f"Target: {target}. Generated by tools/ci/third_party_licenses.py from Cargo.lock.",
        "R-CAD itself is MIT OR Apache-2.0 (LICENSE-MIT, LICENSE-APACHE).",
        "Where a crate offers a choice of licences, it is used under a permissive option",
        "(MIT or Apache-2.0); see docs/DEPENDENCIES.md.",
        "",
        f"{len(pkgs)} crates:",
        "",
    ]
    for p in pkgs:
        ident = f"{p['name']} {p['version']}"
        lines.append(f"- {ident}: {p.get('license') or 'see licence file'}")
        if p.get("authors"):
            lines.append(f"    authors: {', '.join(p['authors'])}")
        if p.get("repository"):
            lines.append(f"    source: {p['repository']}")
        files = licence_files(p)
        if not files:
            bare.append(p)
        for f in files:
            with open(f, encoding="utf-8", errors="replace") as fh:
                t = fh.read().strip()
            h = hashlib.sha256(t.encode()).hexdigest()
            texts.setdefault(h, (t, []))[1].append(f"{ident} ({os.path.basename(f)})")
    lines += ["", "=" * 78, "Licence texts shipped by the crates", "=" * 78]
    for t, users in texts.values():
        lines += ["", "-" * 78, "Used by: " + "; ".join(users), "-" * 78, "", t]

    lines += ["", "=" * 78, "Crates without a licence file in their package", "=" * 78, ""]
    for p in bare:
        holders = ", ".join(p.get("authors") or []) or f"the {p['name']} authors"
        lines.append(f"- {p['name']} {p['version']} ({p.get('license')}): Copyright (c) {holders}")
    lines += [
        "",
        "These crates are distributed under the licence named above. The Apache License 2.0",
        "text is in LICENSE-APACHE alongside this file. For MIT-licensed crates the following",
        "terms apply, with the copyright holders listed above:",
        "",
    ]
    with open("LICENSE-MIT", encoding="utf-8") as fh:
        mit = fh.read()
    lines.append(mit[mit.index("Permission is hereby granted"):].strip())

    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{out}: {len(pkgs)} crates, {len(texts)} distinct licence texts, "
          f"{len(bare)} crates without licence files")


if __name__ == "__main__":
    main()
