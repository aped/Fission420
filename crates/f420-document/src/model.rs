//! Authoritative document data: features, parameters, semantic references.
use crate::{DocError, Result};
use f420_sketch::Sketch;
use serde::{Deserialize, Serialize};
use std::fmt;

/// Stable feature identifier. Allocated monotonically, never reused.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct FeatureId(pub u32);

impl fmt::Display for FeatureId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "F{}", self.0)
    }
}

/// Stable body identifier (ADR 0003). Allocated monotonically from
/// [`Document::next_body_id`], stored in the creating feature, never reused.
/// `BodyId(0)` means "unassigned" and only exists transiently while migrating
/// v1/v2 files.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, Default,
)]
pub struct BodyId(pub u32);

impl fmt::Display for BodyId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "B{}", self.0)
    }
}

/// User-facing body metadata. Geometry comes from the creating feature.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BodyInfo {
    pub id: BodyId,
    pub name: String,
    #[serde(default = "yes")]
    pub visible: bool,
}

fn yes() -> bool {
    true
}

/// Identifier of an embedded binary/text blob (imported source files).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct BlobId(pub u32);

impl fmt::Display for BlobId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "blob{}", self.0)
    }
}

/// An embedded source file (immutable once added). The native document keeps
/// the bytes so it never depends on the original path (ADR 0003).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Blob {
    pub id: BlobId,
    /// Original file name (provenance only; never reopened).
    pub file_name: String,
    /// Size of the decoded bytes.
    pub len: u64,
    /// FNV-1a 64 of the decoded bytes, hex (integrity check, not security).
    pub fnv64: String,
    /// The bytes: UTF-8 text verbatim, or base64.
    pub encoding: BlobEncoding,
    pub data: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum BlobEncoding {
    Text,
    Base64,
}

impl Blob {
    /// Embed `bytes` (stored as text when they are valid UTF-8, else base64).
    pub fn new(id: BlobId, file_name: &str, bytes: &[u8]) -> Self {
        let (encoding, data) = match std::str::from_utf8(bytes) {
            Ok(t) => (BlobEncoding::Text, t.to_string()),
            Err(_) => (BlobEncoding::Base64, crate::blob::base64_encode(bytes)),
        };
        Self {
            id,
            file_name: file_name.to_string(),
            len: bytes.len() as u64,
            fnv64: crate::blob::fnv64_hex(bytes),
            encoding,
            data,
        }
    }

    /// Decoded bytes, verified against the stored length and hash.
    pub fn bytes(&self) -> Result<Vec<u8>> {
        let b = match self.encoding {
            BlobEncoding::Text => self.data.as_bytes().to_vec(),
            BlobEncoding::Base64 => crate::blob::base64_decode(&self.data)
                .ok_or_else(|| DocError::File(format!("{}: invalid base64 data", self.id)))?,
        };
        if b.len() as u64 != self.len || crate::blob::fnv64_hex(&b) != self.fnv64 {
            return Err(DocError::File(format!(
                "{} ({}): embedded data is corrupt (length/hash mismatch)",
                self.id, self.file_name
            )));
        }
        Ok(b)
    }
}

/// Semantic role of a face generated by a feature. Resolved from the generating
/// feature's definition, then validated against the B-rep; never a face index.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum FaceRole {
    /// Planar cap at the end of an extrusion (the "top" for +Z extrusions). For a
    /// blind cut: the floor, outward normal pointing back toward the opening.
    ExtrudeEndCap,
    /// Planar cap at the start of an extrusion (on the profile plane).
    ExtrudeStartCap,
    /// Planar side face generated by profile line `entity` (sketch entity id) of an
    /// extrusion (New/Join: outer wall; Cut: wall of the removed region).
    ExtrudeSide { entity: u32 },
    /// Planar face `face` (stable import index) of imported body `body`.
    Imported { body: BodyId, face: u32 },
}

/// Persistent face selection: originating feature + generated-face role.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct FaceRef {
    pub feature: FeatureId,
    pub role: FaceRole,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum SketchPlane {
    /// World XY plane through the origin, normal +Z.
    WorldXY,
    /// World XZ plane through the origin: local x = world X, local y = world Z, normal -Y.
    WorldXZ,
    /// World YZ plane through the origin: local x = world Y, local y = world Z, normal +X.
    WorldYZ,
    /// A planar face generated by an earlier feature.
    Face(FaceRef),
}

/// What an extrusion does with its tool body (ADR 0003).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Operation {
    /// Create body `body`.
    NewBody { body: BodyId },
    /// Union the tool into `target`.
    Join { target: BodyId },
    /// Subtract the tool from `target`.
    Cut { target: BodyId },
}

impl Default for Operation {
    /// v1/v2 extrusions created the (single) base body; the id is assigned by migration.
    fn default() -> Self {
        Operation::NewBody { body: BodyId(0) }
    }
}

/// How far an extrusion goes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Extent {
    /// `distance` mm along the direction.
    #[default]
    Distance,
    /// Cut only: through all material of the target on both sides of the sketch
    /// plane along its normal (cutter length derived from the target's extent).
    ThroughAll,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum CutExtent {
    /// Through all material, both directions along the sketch normal.
    ThroughAll,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum FeatureKind {
    Sketch {
        plane: SketchPlane,
        sketch: Sketch,
    },
    /// New-body revolve of a sketch profile about the sketch's local Y axis.
    /// `angle` is in radians (exposed as parameter `angle_deg`).
    Revolve {
        sketch: FeatureId,
        angle: f64,
        /// Body created (v3; assigned by migration for older files).
        #[serde(default)]
        body: BodyId,
    },
    /// Extrusion of a sketch profile along the sketch normal (or against it when
    /// `reverse`): a new body, or joined to / cut from an explicit target body.
    Extrude {
        sketch: FeatureId,
        distance: f64,
        #[serde(default)]
        operation: Operation,
        #[serde(default)]
        extent: Extent,
        #[serde(default)]
        reverse: bool,
    },
    /// Legacy (v1/v2) circular through-all cut; see [`FeatureKind::Extrude`] with
    /// [`Operation::Cut`] for general cuts.
    Cut {
        sketch: FeatureId,
        extent: CutExtent,
        #[serde(default)]
        target: BodyId,
    },
    /// Blind cut: removes the sketch profile from the sketched extrusion cap
    /// inward (against the cap's outward normal) to `depth` mm. Product limits:
    /// circular profile sketched on an end/start cap of the base extrusion,
    /// strictly inside it, 0 < depth < extrusion thickness (a through hole is
    /// `Cut`). Added in format v2; absent from v1 files.
    Pocket {
        sketch: FeatureId,
        depth: f64,
        #[serde(default)]
        target: BodyId,
    },
    /// Base feature: exact solids imported from an embedded STEP file. One body
    /// per imported solid (in file order). No source feature history.
    ImportStep {
        blob: BlobId,
        /// Unit scale used when the file declares no length unit (mm per unit).
        #[serde(default)]
        unit_override_to_mm: Option<f64>,
        bodies: Vec<BodyId>,
    },
    /// Base feature: a triangle mesh (STL) body, scaled by `to_mm` (STL is unitless).
    ImportMesh {
        blob: BlobId,
        to_mm: f64,
        body: BodyId,
    },
    /// Repeat the tool of `seed` (an Extrude Cut) `count - 1` more times, each
    /// shifted by `spacing` mm along `direction` (seed sketch-plane coordinates,
    /// normalized), on the seed's target body. The seed is instance 0.
    LinearPattern {
        seed: FeatureId,
        count: u32,
        spacing: f64,
        direction: [f64; 2],
    },
}

impl FeatureKind {
    /// Distance extrusion along the sketch normal.
    pub fn extrude(sketch: FeatureId, distance: f64, operation: Operation) -> Self {
        FeatureKind::Extrude {
            sketch,
            distance,
            operation,
            extent: Extent::Distance,
            reverse: false,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Feature {
    pub id: FeatureId,
    pub name: String,
    pub kind: FeatureKind,
}

impl Feature {
    /// Features this one depends on.
    pub fn dependencies(&self) -> Vec<FeatureId> {
        match &self.kind {
            FeatureKind::Sketch {
                plane: SketchPlane::Face(r),
                ..
            } => vec![r.feature],
            FeatureKind::Sketch { .. } => vec![],
            FeatureKind::Extrude { sketch, .. }
            | FeatureKind::Cut { sketch, .. }
            | FeatureKind::Pocket { sketch, .. }
            | FeatureKind::Revolve { sketch, .. } => vec![*sketch],
            FeatureKind::LinearPattern { seed, .. } => vec![*seed],
            FeatureKind::ImportStep { .. } | FeatureKind::ImportMesh { .. } => vec![],
        }
    }

    /// Bodies this feature creates.
    pub fn created_bodies(&self) -> Vec<BodyId> {
        match &self.kind {
            FeatureKind::Extrude {
                operation: Operation::NewBody { body },
                ..
            }
            | FeatureKind::Revolve { body, .. }
            | FeatureKind::ImportMesh { body, .. } => vec![*body],
            FeatureKind::ImportStep { bodies, .. } => bodies.clone(),
            _ => vec![],
        }
    }

    /// Body this feature modifies (Join/Cut target), if any.
    pub fn target_body(&self) -> Option<BodyId> {
        match &self.kind {
            FeatureKind::Extrude {
                operation: Operation::Join { target } | Operation::Cut { target },
                ..
            }
            | FeatureKind::Cut { target, .. }
            | FeatureKind::Pocket { target, .. } => Some(*target),
            _ => None,
        }
    }

    /// Embedded blob this feature reads, if any.
    pub fn blob(&self) -> Option<BlobId> {
        match &self.kind {
            FeatureKind::ImportStep { blob, .. } | FeatureKind::ImportMesh { blob, .. } => {
                Some(*blob)
            }
            _ => None,
        }
    }

    /// Editable named parameters (mm).
    pub fn parameters(&self) -> Vec<(String, f64)> {
        match &self.kind {
            FeatureKind::Sketch { sketch, .. } => {
                let mut p = sketch.dimensions();
                if let Some((x, y)) = anchor(sketch) {
                    p.push(("center_x".into(), x));
                    p.push(("center_y".into(), y));
                }
                p
            }
            // Unit conversion boundary: degrees for users, radians internally.
            FeatureKind::Revolve { angle, .. } => vec![("angle_deg".into(), angle.to_degrees())],
            FeatureKind::Extrude {
                extent: Extent::ThroughAll,
                ..
            } => vec![],
            FeatureKind::Extrude { distance, .. } => vec![("distance".into(), *distance)],
            FeatureKind::Cut { .. } | FeatureKind::ImportStep { .. } => vec![],
            FeatureKind::ImportMesh { .. } => vec![],
            FeatureKind::Pocket { depth, .. } => vec![("depth".into(), *depth)],
            FeatureKind::LinearPattern { count, spacing, .. } => vec![
                ("count".into(), f64::from(*count)),
                ("spacing".into(), *spacing),
            ],
        }
    }

    /// Set a parameter on the definition only (no regeneration).
    pub fn set_parameter(&mut self, name: &str, value: f64) -> Result<()> {
        let id = self.id;
        if !value.is_finite() {
            return Err(DocError::Validation(format!(
                "{id}.{name}: value must be finite, got {value}"
            )));
        }
        match &mut self.kind {
            // Only template sketches (exactly one fixed anchor, no origin) expose
            // center_x / center_y; on editor sketches the only FixedPoint is the
            // origin, which must never move.
            FeatureKind::Sketch { sketch, .. }
                if (name == "center_x" || name == "center_y") && anchor(sketch).is_some() =>
            {
                let Some(f420_sketch::Constraint::FixedPoint { x, y, .. }) = sketch
                    .constraints
                    .iter_mut()
                    .find(|c| matches!(c, f420_sketch::Constraint::FixedPoint { .. }))
                else {
                    return Err(DocError::UnknownParameter {
                        feature: id,
                        name: name.into(),
                    });
                };
                *(if name == "center_x" { x } else { y }) = value;
                Ok(())
            }
            FeatureKind::Sketch { sketch, .. } => {
                sketch.set_dimension(name, value).map_err(|e| match e {
                    f420_sketch::SketchError::UnknownDimension(_) => DocError::UnknownParameter {
                        feature: id,
                        name: name.into(),
                    },
                    other => DocError::Validation(format!("{id}.{name}: {other}")),
                })?;
                // Store the solved geometry so the definition stays a solved state
                // (freeform vertices are solver unknowns seeded from storage). A
                // failed solve leaves the seed; regeneration then reports it.
                let mut solved = sketch.clone();
                if solved.solve().is_success() {
                    *sketch = solved;
                }
                Ok(())
            }
            FeatureKind::Revolve { angle, .. } if name == "angle_deg" => {
                if value <= 0.0 || value > 360.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.angle_deg: revolve angle must be in (0, 360] degrees, got {value}"
                    )));
                }
                *angle = value.to_radians();
                Ok(())
            }
            FeatureKind::Extrude {
                distance, extent, ..
            } if name == "distance" && *extent == Extent::Distance => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.distance: extrusion thickness must be > 0 mm, got {value}"
                    )));
                }
                *distance = value;
                Ok(())
            }
            FeatureKind::LinearPattern { count, .. } if name == "count" => {
                if value.fract() != 0.0 || !(2.0..=MAX_PATTERN_COUNT as f64).contains(&value) {
                    return Err(DocError::Validation(format!(
                        "{id}.count: pattern count must be an integer in 2..={MAX_PATTERN_COUNT}, \
                         got {value}"
                    )));
                }
                *count = value as u32;
                Ok(())
            }
            FeatureKind::LinearPattern { spacing, .. } if name == "spacing" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.spacing: pattern spacing must be > 0 mm, got {value}"
                    )));
                }
                *spacing = value;
                Ok(())
            }
            FeatureKind::Pocket { depth, .. } if name == "depth" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.depth: pocket depth must be > 0 mm, got {value}"
                    )));
                }
                *depth = value;
                Ok(())
            }
            _ => Err(DocError::UnknownParameter {
                feature: id,
                name: name.into(),
            }),
        }
    }
}

/// Largest linear pattern count (bounds the boolean work of one feature).
pub const MAX_PATTERN_COUNT: u32 = 100;

/// Position of a template sketch's single fixed anchor point (the template centre),
/// exposed as the editable parameters `center_x` / `center_y` (mm, sketch-plane frame).
/// Editor sketches (with an `origin` point) have no movable anchor.
pub fn anchor(sketch: &f420_sketch::Sketch) -> Option<(f64, f64)> {
    if sketch.origin.is_some() {
        return None;
    }
    let mut fixed = sketch.constraints.iter().filter_map(|c| match c {
        f420_sketch::Constraint::FixedPoint { x, y, .. } => Some((*x, *y)),
        _ => None,
    });
    let first = fixed.next()?;
    fixed.next().is_none().then_some(first)
}

/// The authoritative model: ordered feature history plus the id allocator.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct Document {
    pub features: Vec<Feature>,
    pub next_id: u32,
    /// Body metadata (v3), in creation order. See ADR 0003.
    #[serde(default)]
    pub bodies: Vec<BodyInfo>,
    #[serde(default = "one")]
    pub next_body_id: u32,
    /// Embedded imported source files (v3).
    #[serde(default)]
    pub blobs: Vec<Blob>,
    #[serde(default = "one")]
    pub next_blob_id: u32,
}

fn one() -> u32 {
    1
}

impl Document {
    pub fn new() -> Self {
        Self {
            features: Vec::new(),
            next_id: 1,
            bodies: Vec::new(),
            next_body_id: 1,
            blobs: Vec::new(),
            next_blob_id: 1,
        }
    }

    /// Allocate a body id and register its metadata (`name` must be unique;
    /// see [`Document::default_body_name`]).
    pub fn add_body(&mut self, name: impl Into<String>) -> BodyId {
        let id = BodyId(self.next_body_id.clamp(1, u32::MAX - 1));
        self.next_body_id = id.0.saturating_add(1);
        self.bodies.push(BodyInfo {
            id,
            name: name.into(),
            visible: true,
        });
        id
    }

    pub fn body(&self, id: BodyId) -> Result<&BodyInfo> {
        self.bodies
            .iter()
            .find(|b| b.id == id)
            .ok_or_else(|| DocError::Validation(format!("unknown body {id}")))
    }

    pub fn body_mut(&mut self, id: BodyId) -> Result<&mut BodyInfo> {
        self.bodies
            .iter_mut()
            .find(|b| b.id == id)
            .ok_or_else(|| DocError::Validation(format!("unknown body {id}")))
    }

    /// Unique default body name like "Body1".
    pub fn default_body_name(&self) -> String {
        (1..)
            .map(|i| format!("Body{i}"))
            .find(|n| !self.bodies.iter().any(|b| &b.name == n))
            .unwrap_or_else(|| "Body".to_string())
    }

    /// Embed a source file; returns its id.
    pub fn add_blob(&mut self, file_name: &str, bytes: &[u8]) -> BlobId {
        let id = BlobId(self.next_blob_id.clamp(1, u32::MAX - 1));
        self.next_blob_id = id.0.saturating_add(1);
        self.blobs.push(Blob::new(id, file_name, bytes));
        id
    }

    pub fn blob(&self, id: BlobId) -> Result<&Blob> {
        self.blobs
            .iter()
            .find(|b| b.id == id)
            .ok_or_else(|| DocError::Validation(format!("unknown embedded file {id}")))
    }

    /// Feature that creates body `id`.
    pub fn body_creator(&self, id: BodyId) -> Option<FeatureId> {
        self.features
            .iter()
            .find(|f| f.created_bodies().contains(&id))
            .map(|f| f.id)
    }

    /// All features `f` depends on: explicit references plus the creator of
    /// its target body.
    pub fn dependencies_of(&self, f: &Feature) -> Vec<FeatureId> {
        let mut d = f.dependencies();
        if let Some(t) = f.target_body()
            && let Some(c) = self.body_creator(t)
            && !d.contains(&c)
        {
            d.push(c);
        }
        d
    }

    /// Features that depend on `id` (explicitly or through a body target).
    pub fn dependents_of(&self, id: FeatureId) -> Vec<FeatureId> {
        self.features
            .iter()
            .filter(|f| self.dependencies_of(f).contains(&id))
            .map(|f| f.id)
            .collect()
    }

    /// Consistency of bodies and blobs (ADR 0003): every body is created by
    /// exactly one feature and has exactly one metadata entry; targets name
    /// existing bodies; blob references resolve; unused blobs are removed by
    /// [`Document::prune_blobs`], so they are an error here.
    pub fn validate_bodies(&self) -> Result<()> {
        let mut created = std::collections::HashMap::new();
        for f in &self.features {
            for b in f.created_bodies() {
                if b.0 == 0 || b.0 >= self.next_body_id {
                    return Err(DocError::Validation(format!(
                        "{}: body id {b} is unassigned or >= next_body_id {}",
                        f.id, self.next_body_id
                    )));
                }
                if let Some(prev) = created.insert(b, f.id) {
                    return Err(DocError::Validation(format!(
                        "body {b} is created by both {prev} and {}",
                        f.id
                    )));
                }
            }
        }
        let mut seen = std::collections::HashSet::new();
        for info in &self.bodies {
            if !seen.insert(info.id) {
                return Err(DocError::Validation(format!(
                    "duplicate body entry {}",
                    info.id
                )));
            }
            if !created.contains_key(&info.id) {
                return Err(DocError::Validation(format!(
                    "body {} ({}) is not created by any feature",
                    info.id, info.name
                )));
            }
        }
        for (b, f) in &created {
            if !seen.contains(b) {
                return Err(DocError::Validation(format!(
                    "{f}: body {b} has no body entry"
                )));
            }
        }
        for f in &self.features {
            if let Some(t) = f.target_body()
                && !created.contains_key(&t)
            {
                return Err(DocError::BrokenReference {
                    from: f.id,
                    detail: format!("target body {t} does not exist"),
                });
            }
            if let Some(b) = f.blob() {
                self.blob(b).map_err(|_| DocError::BrokenReference {
                    from: f.id,
                    detail: format!("embedded file {b} is missing"),
                })?;
            }
        }
        let mut blob_ids = std::collections::HashSet::new();
        for b in &self.blobs {
            if !blob_ids.insert(b.id) || b.id.0 == 0 || b.id.0 >= self.next_blob_id {
                return Err(DocError::Validation(format!("invalid blob id {}", b.id)));
            }
        }
        Ok(())
    }

    /// Drop embedded files no feature references (after deleting an import).
    pub fn prune_blobs(&mut self) {
        let used: std::collections::HashSet<BlobId> =
            self.features.iter().filter_map(Feature::blob).collect();
        self.blobs.retain(|b| used.contains(&b.id));
    }

    /// Drop body entries no feature creates (after deleting a body's creator).
    pub fn prune_bodies(&mut self) {
        let made: std::collections::HashSet<BodyId> = self
            .features
            .iter()
            .flat_map(Feature::created_bodies)
            .collect();
        self.bodies.retain(|b| made.contains(&b.id));
    }

    pub fn feature(&self, id: FeatureId) -> Result<&Feature> {
        self.features
            .iter()
            .find(|f| f.id == id)
            .ok_or(DocError::UnknownFeature(id))
    }

    pub fn feature_mut(&mut self, id: FeatureId) -> Result<&mut Feature> {
        self.features
            .iter_mut()
            .find(|f| f.id == id)
            .ok_or(DocError::UnknownFeature(id))
    }

    /// Append a feature, allocating its id. Ids saturate at `u32::MAX - 1`; at that
    /// point `evaluation_order` rejects the document instead of wrapping.
    pub fn push(&mut self, name: impl Into<String>, kind: FeatureKind) -> FeatureId {
        let id = FeatureId(self.next_id.clamp(1, u32::MAX - 1));
        self.next_id = id.0.saturating_add(1);
        self.features.push(Feature {
            id,
            name: name.into(),
            kind,
        });
        id
    }

    /// Append a new-body distance extrusion of `sketch`, allocating its body
    /// (default name). Convenience for the common case.
    pub fn push_extrude(
        &mut self,
        name: impl Into<String>,
        sketch: FeatureId,
        distance: f64,
    ) -> FeatureId {
        let body = self.add_body(self.default_body_name());
        self.push(
            name,
            FeatureKind::extrude(sketch, distance, Operation::NewBody { body }),
        )
    }

    /// Unique default name like "Sketch1".
    pub fn default_name(&self, prefix: &str) -> String {
        (1..)
            .map(|i| format!("{prefix}{i}"))
            .find(|n| !self.features.iter().any(|f| &f.name == n))
            .unwrap_or_else(|| prefix.to_string())
    }

    /// Feature ids in a valid evaluation order (Kahn's algorithm, ties broken by
    /// history position for determinism). Errors on unknown ids or cycles.
    pub fn evaluation_order(&self) -> Result<Vec<FeatureId>> {
        let n = self.features.len();
        let pos = |id: FeatureId| self.features.iter().position(|f| f.id == id);
        let mut seen = std::collections::HashSet::new();
        for f in &self.features {
            if !seen.insert(f.id) {
                return Err(DocError::Validation(format!(
                    "duplicate feature id {}",
                    f.id
                )));
            }
            if f.id.0 >= self.next_id {
                return Err(DocError::Validation(format!(
                    "feature id {} >= next_id {}",
                    f.id, self.next_id
                )));
            }
        }
        let mut indeg = vec![0usize; n];
        let mut users: Vec<Vec<usize>> = vec![Vec::new(); n];
        for (i, f) in self.features.iter().enumerate() {
            for d in self.dependencies_of(f) {
                let j = pos(d).ok_or(DocError::BrokenReference {
                    from: f.id,
                    detail: format!("depends on missing feature {d}"),
                })?;
                indeg[i] += 1;
                users[j].push(i);
            }
        }
        let mut ready: std::collections::BTreeSet<usize> =
            (0..n).filter(|&i| indeg[i] == 0).collect();
        let mut order = Vec::with_capacity(n);
        while let Some(i) = ready.pop_first() {
            order.push(self.features[i].id);
            for &u in &users[i] {
                indeg[u] -= 1;
                if indeg[u] == 0 {
                    ready.insert(u);
                }
            }
        }
        if order.len() != n {
            let stuck = (0..n)
                .filter(|&i| indeg[i] > 0)
                .map(|i| self.features[i].id)
                .collect();
            return Err(DocError::Cycle(stuck));
        }
        Ok(order)
    }
}
