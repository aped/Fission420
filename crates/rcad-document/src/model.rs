#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Feature {
    pub id: FeatureId,
    pub name: String,
    pub kind: FeatureKind,
    /// Provenance notes kept with the definition (e.g. DXF/SVG import units,
    /// counts and skipped content). Informational; never affects geometry.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub notes: Vec<String>,
    /// Editable parameters bound to expressions (parameter name -> expression
    /// text, v4; see `params.rs`). The bound values in `kind` are derived from
    /// these by every transaction.
    #[serde(default, skip_serializing_if = "std::collections::BTreeMap::is_empty")]
    pub expressions: std::collections::BTreeMap<String, String>,
    /// Suppressed: kept in history, not evaluated. Nothing that is
    /// evaluated may depend on a suppressed feature
    /// ([`Document::check_suppression`]): dependents are suppressed with it or
    /// the change is refused, never silently rebound. Serde-additive.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub suppressed: bool,
}

impl Feature {
    /// Features this one depends on.
    pub fn dependencies(&self) -> Vec<FeatureId> {
        match &self.kind {
            FeatureKind::Sketch { plane, links, .. } => plane
                .face()
                .map(|r| r.feature)
                .into_iter()
                .chain(links.iter().map(ProjectionLink::source_feature))
                .collect(),
            FeatureKind::Extrude {
                sketch, options, ..
            } => std::iter::once(*sketch)
                .chain(options.to.and_then(|p| p.face()).map(|r| r.feature))
                .collect(),
            FeatureKind::Cut { sketch, .. }
            | FeatureKind::Pocket { sketch, .. }
            | FeatureKind::Revolve { sketch, .. } => vec![*sketch],
            FeatureKind::Loft { a, b, via, .. } => std::iter::once(*a)
                .chain(via.iter().copied())
                .chain([*b])
                .collect(),
            FeatureKind::Sweep { profile, path, .. } => vec![*profile, *path],
            FeatureKind::LinearPattern { seed, .. } | FeatureKind::CircularPattern { seed, .. } => {
                vec![*seed]
            }
            FeatureKind::Mirror { seed, plane } => std::iter::once(*seed)
                .chain(plane.face().map(|r| r.feature))
                .collect(),
            FeatureKind::Chamfer { a, b, .. } | FeatureKind::Fillet { a, b, .. } => {
                let mut v = vec![a.feature];
                if b.feature != a.feature {
                    v.push(b.feature);
                }
                v
            }
            FeatureKind::Hole { plane, .. } => {
                plane.face().map(|r| r.feature).into_iter().collect()
            }
            FeatureKind::Shell { extrude, .. } => vec![*extrude],
            FeatureKind::MoveBody { .. } => vec![],
            FeatureKind::SplitBody { plane, .. } => {
                plane.face().map(|r| r.feature).into_iter().collect()
            }
            FeatureKind::SheetMetal { sketch, .. }
            | FeatureKind::SheetBase { sketch, .. }
            | FeatureKind::SurfacePatch { sketch, .. }
            | FeatureKind::SurfaceExtrude { sketch, .. } => vec![*sketch],
            FeatureKind::SheetFlange { base, .. } | FeatureKind::SheetFlat { base, .. } => {
                vec![*base]
            }
            FeatureKind::ImportSurfaces { .. }
            | FeatureKind::SurfaceStitch { .. }
            | FeatureKind::SurfaceFill { .. }
            | FeatureKind::Thicken { .. }
            | FeatureKind::MeshRepair { .. }
            | FeatureKind::MeshEdit { .. } => vec![],
            FeatureKind::ShellFace { face, .. } => vec![face.feature],
            FeatureKind::ScaleBody { .. } => vec![],
            FeatureKind::AlignBody { from, to, .. } => vec![from.feature, to.feature],
            FeatureKind::DirectEdit { face, .. } => vec![face.feature],
            FeatureKind::Countersink { hole, .. } => vec![*hole],
            // Body creators (target and tools) come from `Document::dependencies_of`.
            FeatureKind::Combine { .. } => vec![],
            FeatureKind::Thread { plane, .. } => {
                plane.face().map(|r| r.feature).into_iter().collect()
            }
            FeatureKind::ImportStep { .. }
            | FeatureKind::ImportMesh { .. }
            | FeatureKind::Import3mf { .. } => vec![],
        }
    }

    /// Bodies this feature creates.
    pub fn created_bodies(&self) -> Vec<BodyId> {
        match &self.kind {
            FeatureKind::Extrude {
                operation: Operation::NewBody { body },
                ..
            }
            | FeatureKind::Revolve {
                body, merge: None, ..
            }
            | FeatureKind::Loft { body, .. }
            | FeatureKind::Sweep { body, .. }
            | FeatureKind::Thread { body, .. }
            | FeatureKind::ImportMesh { body, .. }
            | FeatureKind::MoveBody {
                copy: Some(body), ..
            }
            | FeatureKind::SplitBody { new_body: body, .. }
            | FeatureKind::SheetMetal { body, .. }
            | FeatureKind::SheetBase { body, .. }
            | FeatureKind::SheetFlat { body, .. }
            | FeatureKind::ImportSurfaces { body, .. }
            | FeatureKind::SurfaceStitch { body, .. }
            | FeatureKind::SurfaceFill { body, .. }
            | FeatureKind::Thicken { body, .. }
            | FeatureKind::SurfacePatch { body, .. }
            | FeatureKind::SurfaceExtrude { body, .. }
            | FeatureKind::MeshRepair { body, .. } => vec![*body],
            FeatureKind::ImportStep { bodies, .. } | FeatureKind::Import3mf { bodies, .. } => {
                bodies.clone()
            }
            FeatureKind::MeshEdit {
                body, second_body, ..
            } => std::iter::once(*body).chain(*second_body).collect(),
            _ => vec![],
        }
    }

    /// (source, derived body) of a feature whose new body replaces its
    /// source in the source's component (see [`Document::add_derived_body`]).
    pub fn derived_body(&self) -> Option<(BodyId, BodyId)> {
        match &self.kind {
            FeatureKind::SurfaceStitch { source, body, .. }
            | FeatureKind::SurfaceFill { source, body, .. }
            | FeatureKind::Thicken { source, body, .. }
            | FeatureKind::MeshRepair { source, body, .. }
            | FeatureKind::MeshEdit { source, body, .. } => Some((*source, *body)),
            _ => None,
        }
    }

    /// Body this feature modifies (Join/Cut target), if any.
    pub fn target_body(&self) -> Option<BodyId> {
        match &self.kind {
            FeatureKind::Extrude {
                operation:
                    Operation::Join { target }
                    | Operation::Cut { target }
                    | Operation::Intersect { target },
                ..
            }
            | FeatureKind::Cut { target, .. }
            | FeatureKind::Pocket { target, .. }
            | FeatureKind::Hole { target, .. }
            | FeatureKind::MoveBody { body: target, .. }
            | FeatureKind::SplitBody { body: target, .. }
            | FeatureKind::ScaleBody { body: target, .. }
            | FeatureKind::Combine { target, .. }
            | FeatureKind::SheetFlange { body: target, .. }
            | FeatureKind::Revolve {
                merge:
                    Some(
                        Operation::Join { target }
                        | Operation::Cut { target }
                        | Operation::Intersect { target },
                    ),
                ..
            } => Some(*target),
            FeatureKind::DirectEdit {
                face:
                    FaceRef {
                        role: FaceRole::Imported { body, .. },
                        ..
                    },
                ..
            } => Some(*body),
            _ => None,
        }
    }

    /// Bodies a [`FeatureKind::Combine`] reads besides its target.
    pub fn tool_bodies(&self) -> Vec<BodyId> {
        match &self.kind {
            FeatureKind::Combine { tools, .. } => tools.clone(),
            // Surface operations read their source body (kept).
            FeatureKind::SurfaceStitch { source, .. }
            | FeatureKind::SurfaceFill { source, .. }
            | FeatureKind::Thicken { source, .. }
            | FeatureKind::MeshRepair { source, .. }
            | FeatureKind::MeshEdit { source, .. } => vec![*source],
            _ => vec![],
        }
    }

    /// Embedded blob this feature reads, if any.
    pub fn blob(&self) -> Option<BlobId> {
        match &self.kind {
            FeatureKind::ImportStep { blob, .. }
            | FeatureKind::ImportMesh { blob, .. }
            | FeatureKind::Import3mf { blob, .. }
            | FeatureKind::ImportSurfaces { blob, .. } => Some(*blob),
            _ => None,
        }
    }

    /// Editable named parameters (mm).
    pub fn parameters(&self) -> Vec<(String, f64)> {
        match &self.kind {
            FeatureKind::Sketch { sketch, plane, .. } => {
                let mut p = sketch.dimensions();
                // Each text's cap height (stored outlines are rescaled).
                for t in &sketch.texts {
                    p.push((format!("text{}_height", t.id), t.spec.height));
                }
                if let Some((x, y)) = anchor(sketch) {
                    p.push(("center_x".into(), x));
                    p.push(("center_y".into(), y));
                }
                if let SketchPlane::Offset {
                    distance, angle, ..
                } = plane
                {
                    p.push(("plane_offset".into(), *distance));
                    p.push(("plane_angle_deg".into(), angle.to_degrees()));
                }
                p
            }
            // Unit conversion boundary: degrees for users, radians internally.
            FeatureKind::Revolve { angle, .. } => vec![("angle_deg".into(), angle.to_degrees())],
            FeatureKind::Extrude {
                extent: Extent::ThroughAll,
                ..
            } => vec![],
            FeatureKind::Extrude {
                distance, options, ..
            } => {
                let mut v = Vec::new();
                if options.to.is_none() {
                    v.push(("distance".into(), *distance));
                }
                if options.distance2 != 0.0 {
                    v.push(("distance2".into(), options.distance2));
                }
                if options.start_offset != 0.0 {
                    v.push(("start_offset".into(), options.start_offset));
                }
                if let Some(t) = options.thin {
                    v.push(("thin".into(), t));
                }
                if options.taper != 0.0 {
                    v.push(("taper_deg".into(), options.taper.to_degrees()));
                }
                match options.to {
                    Some(SketchPlane::Offset { distance, .. }) => {
                        v.push(("to_offset".into(), distance));
                    }
                    Some(_) => v.push(("to_offset".into(), 0.0)),
                    None => {}
                }
                v
            }
            // An offset mirror plane's distance is a parameter.
            FeatureKind::Mirror {
                plane:
                    SketchPlane::Offset {
                        distance, angle, ..
                    },
                ..
            } => vec![
                ("plane_offset".into(), *distance),
                ("plane_angle_deg".into(), angle.to_degrees()),
            ],
            FeatureKind::Cut { .. }
            | FeatureKind::ImportStep { .. }
            | FeatureKind::Mirror { .. } => {
                vec![]
            }
            FeatureKind::ImportMesh { .. } | FeatureKind::Import3mf { .. } => vec![],
            FeatureKind::Loft { .. } | FeatureKind::Sweep { .. } => vec![],
            FeatureKind::Thread {
                diameter,
                pitch,
                length,
                nut,
                ..
            } => {
                let mut v = vec![
                    ("diameter".into(), *diameter),
                    ("pitch".into(), *pitch),
                    ("length".into(), *length),
                ];
                if let Some(n) = nut {
                    v.push(("nut_width".into(), n.width));
                    v.push(("clearance".into(), n.clearance));
                }
                v
            }
            FeatureKind::Pocket { depth, .. } => vec![("depth".into(), *depth)],
            FeatureKind::Chamfer { distance, .. } => vec![("distance".into(), *distance)],
            FeatureKind::Fillet { radius, .. } => vec![("radius".into(), *radius)],
            FeatureKind::Shell { thickness, .. } => vec![("thickness".into(), *thickness)],
            FeatureKind::Combine { .. } => vec![],
            FeatureKind::Countersink {
                diameter, angle, ..
            } => vec![
                ("diameter".into(), *diameter),
                ("angle_deg".into(), angle.to_degrees()),
            ],
            FeatureKind::SplitBody {
                plane:
                    SketchPlane::Offset {
                        distance, angle, ..
                    },
                ..
            } => vec![
                ("plane_offset".into(), *distance),
                ("plane_angle_deg".into(), angle.to_degrees()),
            ],
            FeatureKind::SplitBody { .. } => vec![],
            FeatureKind::ShellFace { thickness, .. } => vec![("thickness".into(), *thickness)],
            FeatureKind::ScaleBody { factor, .. } => vec![("factor".into(), *factor)],
            FeatureKind::AlignBody { offset, .. } => vec![("offset".into(), *offset)],
            FeatureKind::SheetMetal {
                thickness,
                radius,
                k_factor,
                width,
                ..
            } => vec![
                ("thickness".into(), *thickness),
                ("radius".into(), *radius),
                ("k_factor".into(), *k_factor),
                ("width".into(), *width),
            ],
            FeatureKind::SheetBase { rule, .. } => rule.parameters(),
            FeatureKind::SheetFlange {
                angle,
                length,
                start_offset,
                end_offset,
                ..
            } => vec![
                ("angle_deg".into(), angle.to_degrees()),
                ("length".into(), *length),
                ("start_offset".into(), *start_offset),
                ("end_offset".into(), *end_offset),
            ],
            FeatureKind::SurfaceStitch { tolerance, .. }
            | FeatureKind::SurfaceFill { tolerance, .. } => {
                vec![("tolerance".into(), *tolerance)]
            }
            FeatureKind::Thicken { distance, .. }
            | FeatureKind::SurfaceExtrude { distance, .. } => {
                vec![("distance".into(), *distance)]
            }
            FeatureKind::SurfacePatch { .. } => vec![],
            FeatureKind::MeshRepair { options, .. } => {
                vec![("weld_tolerance".into(), options.weld_tolerance)]
            }
            FeatureKind::MeshEdit { op, .. } => crate::mesh_edit::parameters(op),
            FeatureKind::SheetFlat { .. } | FeatureKind::ImportSurfaces { .. } => vec![],
            FeatureKind::MoveBody {
                translate, angle, ..
            } => vec![
                ("tx".into(), translate[0]),
                ("ty".into(), translate[1]),
                ("tz".into(), translate[2]),
                ("angle_deg".into(), angle.to_degrees()),
            ],
            FeatureKind::DirectEdit { op, .. } => match op {
                DirectOp::OffsetFace { distance } => vec![("distance".into(), *distance)],
                DirectOp::ResizeCylinder { diameter } => vec![("diameter".into(), *diameter)],
                DirectOp::RemoveCylinder => vec![],
                DirectOp::ReplaceFace { distance, angle } => vec![
                    ("distance".into(), *distance),
                    ("angle_deg".into(), angle.to_degrees()),
                ],
            },
            FeatureKind::Hole {
                center,
                diameter,
                depth,
                counterbore,
                plane,
                ..
            } => {
                let mut v = vec![("diameter".into(), *diameter)];
                if let Some(d) = depth {
                    v.push(("depth".into(), *d));
                }
                if let Some(c) = counterbore {
                    v.push(("cbore_diameter".into(), c.diameter));
                    v.push(("cbore_depth".into(), c.depth));
                }
                v.push(("center_x".into(), center[0]));
                v.push(("center_y".into(), center[1]));
                if let SketchPlane::Offset {
                    distance, angle, ..
                } = plane
                {
                    v.push(("plane_offset".into(), *distance));
                    v.push(("plane_angle_deg".into(), angle.to_degrees()));
                }
                v
            }
            FeatureKind::LinearPattern { count, spacing, .. } => vec![
                ("count".into(), f64::from(*count)),
                ("spacing".into(), *spacing),
            ],
            FeatureKind::CircularPattern { count, angle, .. } => vec![
                ("count".into(), f64::from(*count)),
                ("angle_deg".into(), angle.to_degrees()),
            ],
        }
    }

    /// Set several parameters at once; on error the feature is unchanged and
    /// the failing slot is named. Hole sizes are validated in their final
    /// combination (a depth and its counterbore depth may change together).
    pub fn set_parameters(
        &mut self,
        values: &[(String, f64)],
    ) -> std::result::Result<(), (String, DocError)> {
        let mut trial = self.clone();
        if let FeatureKind::Hole {
            center,
            diameter,
            depth,
            counterbore,
            plane,
            ..
        } = &mut trial.kind
        {
            for (n, v) in values {
                match (n.as_str(), counterbore.as_mut(), depth.as_mut()) {
                    ("plane_offset", ..) if matches!(plane, SketchPlane::Offset { .. }) => {
                        if let SketchPlane::Offset { distance, .. } = plane {
                            *distance = *v;
                        }
                    }
                    ("plane_angle_deg", ..) if matches!(plane, SketchPlane::Offset { .. }) => {
                        if let SketchPlane::Offset { angle, .. } = plane {
                            *angle = v.to_radians();
                        }
                    }
                    ("diameter", ..) => *diameter = *v,
                    ("depth", _, Some(d)) => *d = *v,
                    ("cbore_diameter", Some(c), _) => c.diameter = *v,
                    ("cbore_depth", Some(c), _) => c.depth = *v,
                    ("center_x", ..) => center[0] = *v,
                    ("center_y", ..) => center[1] = *v,
                    _ => {
                        return Err((
                            n.clone(),
                            DocError::UnknownParameter {
                                feature: self.id,
                                name: n.clone(),
                            },
                        ));
                    }
                }
            }
            // Validate the final combination: re-setting each value checks it
            // against its (final) partners.
            for (n, v) in values {
                trial
                    .clone()
                    .set_parameter(n, *v)
                    .map_err(|e| (n.clone(), e))?;
            }
        } else {
            for (n, v) in values {
                trial.set_parameter(n, *v).map_err(|e| (n.clone(), e))?;
            }
        }
        *self = trial;
        Ok(())
    }

    /// Set a parameter on the definition only (no regeneration).
    pub fn set_parameter(&mut self, name: &str, value: f64) -> Result<()> {
        let id = self.id;
        if !value.is_finite() {
            return Err(DocError::Validation(format!(
                "{id}.{name}: value must be finite, got {value}"
            )));
        }
        match &mut self.kind {
            // Only template sketches (exactly one fixed anchor, no origin) expose
            // center_x / center_y; on editor sketches the only FixedPoint is the
            // origin, which must never move.
            FeatureKind::Sketch { sketch, .. }
                if (name == "center_x" || name == "center_y") && anchor(sketch).is_some() =>
            {
                let Some(rcad_sketch::Constraint::FixedPoint { x, y, .. }) = sketch
                    .constraints
                    .iter_mut()
                    .find(|c| matches!(c, rcad_sketch::Constraint::FixedPoint { .. }))
                else {
                    return Err(DocError::UnknownParameter {
                        feature: id,
                        name: name.into(),
                    });
                };
                *(if name == "center_x" { x } else { y }) = value;
                Ok(())
            }
            FeatureKind::Sketch {
                plane: SketchPlane::Offset { angle, .. },
                ..
            }
            | FeatureKind::Mirror {
                plane: SketchPlane::Offset { angle, .. },
                ..
            }
            | FeatureKind::Hole {
                plane: SketchPlane::Offset { angle, .. },
                ..
            }
            | FeatureKind::SplitBody {
                plane: SketchPlane::Offset { angle, .. },
                ..
            } if name == "plane_angle_deg" => {
                if !(value.is_finite() && value.abs() < 180.0) {
                    return Err(DocError::Validation(format!(
                        "{id}.plane_angle_deg: the plane angle must be in (-180, 180) degrees, \
                         got {value}"
                    )));
                }
                *angle = value.to_radians();
                Ok(())
            }
            FeatureKind::Sketch {
                plane: SketchPlane::Offset { distance, .. },
                ..
            }
            | FeatureKind::Mirror {
                plane: SketchPlane::Offset { distance, .. },
                ..
            }
            | FeatureKind::Hole {
                plane: SketchPlane::Offset { distance, .. },
                ..
            }
            | FeatureKind::SplitBody {
                plane: SketchPlane::Offset { distance, .. },
                ..
            } if name == "plane_offset" => {
                if !value.is_finite() {
                    return Err(DocError::Validation(format!(
                        "{id}.plane_offset: the plane offset must be finite, got {value}"
                    )));
                }
                *distance = value;
                Ok(())
            }
            FeatureKind::Sketch { sketch, .. }
                if name
                    .strip_prefix("text")
                    .and_then(|r| r.strip_suffix("_height"))
                    .and_then(|n| n.parse::<u32>().ok())
                    .is_some_and(|n| sketch.texts.iter().any(|t| t.id == n)) =>
            {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.{name}: text height must be > 0 mm, got {value}"
                    )));
                }
                let n: u32 = name["text".len()..name.len() - "_height".len()]
                    .parse()
                    .unwrap_or(0);
                if let Some(t) = sketch.texts.iter_mut().find(|t| t.id == n) {
                    t.spec.height = value;
                }
                Ok(())
            }
            FeatureKind::Sketch { sketch, .. } => {
                sketch.set_dimension(name, value).map_err(|e| match e {
                    rcad_sketch::SketchError::UnknownDimension(_) => DocError::UnknownParameter {
                        feature: id,
                        name: name.into(),
                    },
                    other => DocError::Validation(format!("{id}.{name}: {other}")),
                })?;
                // Store the solved geometry so the definition stays a solved state
                // (freeform vertices are solver unknowns seeded from storage). A
                // failed solve leaves the seed; regeneration then reports it.
                let mut solved = sketch.clone();
                if solved.solve().is_success() {
                    *sketch = solved;
                }
                Ok(())
            }
            FeatureKind::Revolve { angle, .. } if name == "angle_deg" => {
                if value <= 0.0 || value > 360.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.angle_deg: revolve angle must be in (0, 360] degrees, got {value}"
                    )));
                }
                *angle = value.to_radians();
                Ok(())
            }
            FeatureKind::Extrude {
                options, extent, ..
            } if *extent == Extent::Distance
                && matches!(
                    name,
                    "distance2" | "start_offset" | "thin" | "taper_deg" | "to_offset"
                ) =>
            {
                let has = |b: bool| -> Result<()> {
                    if b {
                        Ok(())
                    } else {
                        Err(DocError::UnknownParameter {
                            feature: id,
                            name: name.into(),
                        })
                    }
                };
                match name {
                    "distance2" => {
                        has(options.distance2 != 0.0)?;
                        if value <= 0.0 {
                            return Err(DocError::Validation(format!(
                                "{id}.distance2: the second side's distance must be > 0 mm, \
                                 got {value}"
                            )));
                        }
                        options.distance2 = value;
                    }
                    "start_offset" => {
                        has(options.start_offset != 0.0)?;
                        options.start_offset = value;
                    }
                    "thin" => {
                        has(options.thin.is_some())?;
                        if value <= 0.0 {
                            return Err(DocError::Validation(format!(
                                "{id}.thin: the wall thickness must be > 0 mm, got {value}"
                            )));
                        }
                        options.thin = Some(value);
                    }
                    "taper_deg" => {
                        has(options.taper != 0.0)?;
                        if value == 0.0 || value.abs() >= 89.0 {
                            return Err(DocError::Validation(format!(
                                "{id}.taper_deg: the taper must be non-zero and within ±89°, \
                                 got {value}"
                            )));
                        }
                        options.taper = value.to_radians();
                    }
                    _ => match options.to.as_mut() {
                        Some(SketchPlane::Offset { distance, .. }) => *distance = value,
                        Some(p) => {
                            let base = match *p {
                                SketchPlane::WorldXY => PlaneBase::WorldXY,
                                SketchPlane::WorldXZ => PlaneBase::WorldXZ,
                                SketchPlane::WorldYZ => PlaneBase::WorldYZ,
                                SketchPlane::Face(r) => PlaneBase::Face(r),
                                SketchPlane::Offset { .. } => unreachable!("matched above"),
                            };
                            *p = SketchPlane::Offset {
                                base,
                                distance: value,
                                angle: 0.0,
                            };
                        }
                        None => has(false)?,
                    },
                }
                Ok(())
            }
            FeatureKind::Extrude {
                distance,
                extent,
                options,
                ..
            } if name == "distance" && *extent == Extent::Distance && options.to.is_none() => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.distance: extrusion thickness must be > 0 mm, got {value}"
                    )));
                }
                *distance = value;
                Ok(())
            }
            FeatureKind::LinearPattern { count, .. }
            | FeatureKind::CircularPattern { count, .. }
                if name == "count" =>
            {
                if value.fract() != 0.0 || !(1.0..=MAX_PATTERN_COUNT as f64).contains(&value) {
                    return Err(DocError::Validation(format!(
                        "{id}.count: pattern count must be an integer in 1..={MAX_PATTERN_COUNT} \
                         (1 = the seed only), got {value}"
                    )));
                }
                *count = value as u32;
                Ok(())
            }
            FeatureKind::CircularPattern { angle, .. } if name == "angle_deg" => {
                if value <= 0.0 || value >= 360.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.angle_deg: angle between instances must be in (0, 360) degrees, \
                         got {value}"
                    )));
                }
                *angle = value.to_radians();
                Ok(())
            }
            FeatureKind::SheetMetal {
                thickness,
                radius,
                k_factor,
                width,
                ..
            } if matches!(name, "thickness" | "radius" | "k_factor" | "width") => {
                let ok = match name {
                    "k_factor" => (0.0..=1.0).contains(&value),
                    _ => value > 0.0,
                };
                if !ok {
                    return Err(DocError::Validation(format!(
                        "{id}.{name}: {}, got {value}",
                        if name == "k_factor" {
                            "the K-factor must be in [0, 1]"
                        } else {
                            "must be > 0 mm"
                        }
                    )));
                }
                *match name {
                    "thickness" => thickness,
                    "radius" => radius,
                    "k_factor" => k_factor,
                    _ => width,
                } = value;
                Ok(())
            }
            FeatureKind::SheetBase { rule, .. }
                if matches!(
                    name,
                    "thickness" | "radius" | "k_factor" | "relief_width" | "relief_depth"
                ) =>
            {
                rule.set(id, name, value)?;
                Ok(())
            }
            FeatureKind::SheetFlange {
                angle,
                length,
                start_offset,
                end_offset,
                ..
            } if matches!(name, "angle_deg" | "length" | "start_offset" | "end_offset") => {
                let ok = match name {
                    "angle_deg" => value > 0.0 && value <= 180.0,
                    "length" => value > 0.0,
                    _ => value >= 0.0,
                };
                if !ok {
                    return Err(DocError::Validation(format!(
                        "{id}.{name}: {}, got {value}",
                        match name {
                            "angle_deg" => "the bend angle must be in (0, 180] degrees",
                            "length" => "must be > 0 mm",
                            _ => "must be >= 0 mm",
                        }
                    )));
                }
                match name {
                    "angle_deg" => *angle = value.to_radians(),
                    "length" => *length = value,
                    "start_offset" => *start_offset = value,
                    _ => *end_offset = value,
                }
                Ok(())
            }
            FeatureKind::MeshEdit { op, .. } => {
                crate::mesh_edit::set_parameter(id, op, name, value)
            }
            FeatureKind::MeshRepair { options, .. } if name == "weld_tolerance" => {
                let mut o = *options;
                o.weld_tolerance = value;
                o.validate()
                    .map_err(|e| DocError::Validation(format!("{id}.weld_tolerance: {e}")))?;
                *options = o;
                Ok(())
            }
            FeatureKind::SurfaceStitch { tolerance, .. }
            | FeatureKind::SurfaceFill { tolerance, .. }
                if name == "tolerance" =>
            {
                if !(0.0..=1.0).contains(&value) {
                    return Err(DocError::Validation(format!(
                        "{id}.tolerance: the healing tolerance must be in [0, 1] mm, got {value}"
                    )));
                }
                *tolerance = value;
                Ok(())
            }
            FeatureKind::Thicken { distance, .. }
            | FeatureKind::SurfaceExtrude { distance, .. }
                if name == "distance" =>
            {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.distance: must be > 0 mm, got {value}"
                    )));
                }
                *distance = value;
                Ok(())
            }
            FeatureKind::MoveBody {
                translate, angle, ..
            } if matches!(name, "tx" | "ty" | "tz" | "angle_deg") => {
                match name {
                    "tx" => translate[0] = value,
                    "ty" => translate[1] = value,
                    "tz" => translate[2] = value,
                    _ => {
                        if value.abs() > 360.0 {
                            return Err(DocError::Validation(format!(
                                "{id}.angle_deg: the rotation must be within ±360°, got {value}"
                            )));
                        }
                        *angle = value.to_radians();
                    }
                }
                Ok(())
            }
            FeatureKind::AlignBody { offset, .. } if name == "offset" => {
                *offset = value;
                Ok(())
            }
            FeatureKind::ScaleBody { factor, .. } if name == "factor" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.factor: the scale factor must be > 0, got {value}"
                    )));
                }
                *factor = value;
                Ok(())
            }
            FeatureKind::Shell { thickness, .. } | FeatureKind::ShellFace { thickness, .. }
                if name == "thickness" =>
            {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.thickness: shell wall thickness must be > 0 mm, got {value}"
                    )));
                }
                *thickness = value;
                Ok(())
            }
            FeatureKind::LinearPattern { spacing, .. } if name == "spacing" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.spacing: pattern spacing must be > 0 mm, got {value}"
                    )));
                }
                *spacing = value;
                Ok(())
            }
            FeatureKind::Hole {
                center,
                diameter,
                depth,
                counterbore,
                ..
            } => {
                let pos = |what: &str| {
                    (value > 0.0).then_some(()).ok_or_else(|| {
                        DocError::Validation(format!(
                            "{id}.{name}: {what} must be > 0 mm, got {value}"
                        ))
                    })
                };
                match (name, counterbore.as_mut(), depth.as_mut()) {
                    ("diameter", cb, _) => {
                        pos("hole diameter")?;
                        if let Some(c) = cb
                            && c.diameter <= value
                        {
                            return Err(DocError::Validation(format!(
                                "{id}.diameter: the hole ({value} mm) must be smaller than its \
                                 counterbore ({} mm)",
                                c.diameter
                            )));
                        }
                        *diameter = value;
                    }
                    ("depth", cb, Some(d)) => {
                        pos("hole depth")?;
                        if let Some(c) = cb
                            && c.depth >= value
                        {
                            return Err(DocError::Validation(format!(
                                "{id}.depth: the hole ({value} mm) must be deeper than its \
                                 counterbore ({} mm)",
                                c.depth
                            )));
                        }
                        *d = value;
                    }
                    ("cbore_diameter", Some(c), _) => {
                        if value <= *diameter {
                            return Err(DocError::Validation(format!(
                                "{id}.cbore_diameter: the counterbore ({value} mm) must be wider \
                                 than the hole ({diameter} mm)"
                            )));
                        }
                        c.diameter = value;
                    }
                    ("cbore_depth", Some(c), d) => {
                        pos("counterbore depth")?;
                        if let Some(d) = d
                            && value >= *d
                        {
                            return Err(DocError::Validation(format!(
                                "{id}.cbore_depth: the counterbore ({value} mm) must be shallower \
                                 than the hole ({d} mm)"
                            )));
                        }
                        c.depth = value;
                    }
                    ("center_x", _, _) => center[0] = value,
                    ("center_y", _, _) => center[1] = value,
                    _ => {
                        return Err(DocError::UnknownParameter {
                            feature: id,
                            name: name.into(),
                        });
                    }
                }
                Ok(())
            }
            FeatureKind::Thread {
                diameter,
                pitch,
                length,
                nut,
                ..
            } if matches!(
                name,
                "diameter" | "pitch" | "length" | "nut_width" | "clearance"
            ) =>
            {
                let slot = match (name, nut.as_mut()) {
                    ("diameter", _) => diameter,
                    ("pitch", _) => pitch,
                    ("length", _) => length,
                    ("nut_width", Some(n)) => &mut n.width,
                    ("clearance", Some(n)) => &mut n.clearance,
                    _ => {
                        return Err(DocError::UnknownParameter {
                            feature: id,
                            name: name.into(),
                        });
                    }
                };
                if value < 0.0 || (value == 0.0 && name != "clearance") {
                    return Err(DocError::Validation(format!(
                        "{id}.{name}: must be > 0 mm, got {value}"
                    )));
                }
                *slot = value;
                Ok(())
            }
            FeatureKind::Countersink { diameter, .. } if name == "diameter" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.diameter: countersink diameter must be > 0 mm, got {value}"
                    )));
                }
                *diameter = value;
                Ok(())
            }
            FeatureKind::Countersink { angle, .. } if name == "angle_deg" => {
                if !(value > 0.0 && value < 180.0) {
                    return Err(DocError::Validation(format!(
                        "{id}.angle_deg: countersink angle must be between 0 and 180 degrees, \
                         got {value}"
                    )));
                }
                *angle = value.to_radians();
                Ok(())
            }
            FeatureKind::DirectEdit {
                op: DirectOp::OffsetFace { distance },
                ..
            } if name == "distance" => {
                if value == 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.distance: a face offset must be non-zero"
                    )));
                }
                *distance = value;
                Ok(())
            }
            FeatureKind::DirectEdit {
                op: DirectOp::ReplaceFace { distance, .. },
                ..
            } if name == "distance" => {
                *distance = value;
                Ok(())
            }
            FeatureKind::DirectEdit {
                op: DirectOp::ReplaceFace { angle, .. },
                ..
            } if name == "angle_deg" => {
                if value.abs() >= 89.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.angle_deg: the tilt must be below 89 degrees, got {value}"
                    )));
                }
                *angle = value.to_radians();
                Ok(())
            }
            FeatureKind::DirectEdit {
                op: DirectOp::ResizeCylinder { diameter },
                ..
            } if name == "diameter" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.diameter: diameter must be > 0 mm, got {value}"
                    )));
                }
                *diameter = value;
                Ok(())
            }
            FeatureKind::Fillet { radius, .. } if name == "radius" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.radius: fillet radius must be > 0 mm, got {value}"
                    )));
                }
                *radius = value;
                Ok(())
            }
            FeatureKind::Chamfer { distance, .. } if name == "distance" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.distance: chamfer distance must be > 0 mm, got {value}"
                    )));
                }
                *distance = value;
                Ok(())
            }
            FeatureKind::Pocket { depth, .. } if name == "depth" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.depth: pocket depth must be > 0 mm, got {value}"
                    )));
                }
                *depth = value;
                Ok(())
            }
            _ => Err(DocError::UnknownParameter {
                feature: id,
                name: name.into(),
            }),
        }
    }
}

/// Largest linear pattern count (bounds the boolean work of one feature).
pub const MAX_PATTERN_COUNT: u32 = 100;

/// Position of a template sketch's single fixed anchor point (the template centre),
/// exposed as the editable parameters `center_x` / `center_y` (mm, sketch-plane frame).
/// Editor sketches (with an `origin` point) have no movable anchor.
pub fn anchor(sketch: &rcad_sketch::Sketch) -> Option<(f64, f64)> {
    if sketch.origin.is_some() {
        return None;
    }
    let mut fixed = sketch.constraints.iter().filter_map(|c| match c {
        rcad_sketch::Constraint::FixedPoint { x, y, .. } => Some((*x, *y)),
        _ => None,
    });
    let first = fixed.next()?;
    fixed.next().is_none().then_some(first)
}

/// The authoritative model: ordered feature history plus the id allocator.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct Document {
    pub features: Vec<Feature>,
    pub next_id: u32,
    /// Body metadata (v3), in creation order. See ADR 0003.
    #[serde(default)]
    pub bodies: Vec<BodyInfo>,
    #[serde(default = "one")]
    pub next_body_id: u32,
    /// Embedded imported source files (v3).
    #[serde(default)]
    pub blobs: Vec<Blob>,
    #[serde(default = "one")]
    pub next_blob_id: u32,
    /// Named user parameters (v4), in display order.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub parameters: Vec<crate::Parameter>,
    /// Timeline marker (format v6): history is evaluated up to and
    /// including this feature; later features are rolled back (kept, not
    /// evaluated) and new features are inserted right after it (the marker
    /// then moves to the new feature). None: at the end.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub rollback: Option<FeatureId>,
    /// Named configurations (format v6):
    /// per configuration, user-parameter expressions, the suppression state
    /// of the configured features, and a part number. Activating one applies
    /// it in one transaction (`Document::apply_configuration`).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub configurations: Vec<Configuration>,
    /// The configuration last activated (None: none / not configured).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub active_configuration: Option<String>,
    /// Components, occurrences and joints (format v6; docs/ASSEMBLIES.md).
    #[serde(default, skip_serializing_if = "crate::assembly::Assembly::is_empty")]
    pub assembly: crate::assembly::Assembly,
    /// Drawing sheets (format v6; docs/DRAWINGS.md). Views reference
    /// bodies by id; geometry is computed at export from the evaluation.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub drawings: Vec<crate::drawing::Drawing>,
}

/// A named variant of a document (see [`Document::configurations`]).
/// `values` override user-parameter expressions; every feature in
/// `controls` is suppressed when it is in `suppressed`, evaluated otherwise
/// (features no configuration controls keep their own state).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct Configuration {
    pub name: String,
    #[serde(default, skip_serializing_if = "std::collections::BTreeMap::is_empty")]
    pub values: std::collections::BTreeMap<String, String>,
    #[serde(default, skip_serializing_if = "std::collections::BTreeSet::is_empty")]
    pub suppressed: std::collections::BTreeSet<FeatureId>,
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub part_number: String,
    /// Component occurrences this configuration excludes; every
    /// occurrence any configuration lists is controlled like `suppressed`.
    #[serde(default, skip_serializing_if = "std::collections::BTreeSet::is_empty")]
    pub excluded_occurrences: std::collections::BTreeSet<crate::assembly::OccurrenceId>,
}

fn one() -> u32 {
    1
}

impl Document {
    pub fn new() -> Self {
        Self {
            features: Vec::new(),
            next_id: 1,
            bodies: Vec::new(),
            next_body_id: 1,
            blobs: Vec::new(),
            next_blob_id: 1,
            parameters: Vec::new(),
            rollback: None,
            configurations: Vec::new(),
            active_configuration: None,
            assembly: Default::default(),
            drawings: Vec::new(),
        }
    }

    /// Features any configuration controls (suppressed in at least one).
    pub fn configured_features(&self) -> std::collections::BTreeSet<FeatureId> {
        self.configurations
            .iter()
            .flat_map(|c| c.suppressed.iter().copied())
            .collect()
    }

    /// Apply configuration `name` to this document: set its parameter
    /// expressions (each parameter must exist), suppress the configured
    /// features it lists and restore the other configured features, and mark
    /// it active. Dependents of a suppressed feature must be suppressed by the
    /// same configuration (`check_suppression` refuses otherwise).
    pub fn apply_configuration(&mut self, name: &str) -> Result<()> {
        let c = self
            .configurations
            .iter()
            .find(|c| c.name == name)
            .cloned()
            .ok_or_else(|| DocError::Validation(format!("no configuration named '{name}'")))?;
        for (p, e) in &c.values {
            let x = self
                .parameters
                .iter_mut()
                .find(|x| x.name == *p)
                .ok_or_else(|| DocError::Expression {
                    name: p.clone(),
                    detail: format!("configuration '{name}' sets a parameter that does not exist"),
                })?;
            x.expression = e.clone();
        }
        for f in self.configured_features() {
            self.feature_mut(f)?.suppressed = c.suppressed.contains(&f);
        }
        let controlled: std::collections::BTreeSet<_> = self
            .configurations
            .iter()
            .flat_map(|x| x.excluded_occurrences.iter().copied())
            .collect();
        for o in self.assembly.occurrences.iter_mut() {
            if controlled.contains(&o.id) {
                o.suppressed = c.excluded_occurrences.contains(&o.id);
            }
        }
        self.active_configuration = Some(name.to_string());
        self.check_suppression()
    }

    /// Drop configuration values for parameters that do
    /// not exist (left by a parameter rename or delete before configurations
    /// followed them); such a configuration could not be activated. One line
    /// per configuration with the dropped names.
    pub fn prune_configuration_values(&mut self) -> Vec<String> {
        let names: std::collections::BTreeSet<&str> =
            self.parameters.iter().map(|p| p.name.as_str()).collect();
        let mut out = Vec::new();
        for c in &mut self.configurations {
            let stale: Vec<String> = c
                .values
                .keys()
                .filter(|k| !names.contains(k.as_str()))
                .cloned()
                .collect();
            if stale.is_empty() {
                continue;
            }
            for k in &stale {
                c.values.remove(k);
            }
            out.push(format!(
                "configuration '{}': removed values for missing parameter(s) {}",
                c.name,
                stale.join(", ")
            ));
        }
        out
    }

    /// Drop configuration exclusions of occurrences that no longer exist;
    /// returns how many were removed.
    pub fn prune_configuration_occurrences(&mut self) -> usize {
        let live: std::collections::BTreeSet<_> =
            self.assembly.occurrences.iter().map(|o| o.id).collect();
        let mut n = 0;
        for c in &mut self.configurations {
            let before = c.excluded_occurrences.len();
            c.excluded_occurrences.retain(|o| live.contains(o));
            n += before - c.excluded_occurrences.len();
        }
        n
    }

    /// Register a body that never joins the active component: display or
    /// derived bodies (flat patterns, repaired/stitched/thickened results)
    /// whose source decides their component.
    pub fn add_body_unowned(&mut self, name: impl Into<String>) -> BodyId {
        let active = self.assembly.active.take();
        let id = self.add_body(name);
        self.assembly.active = active;
        id
    }

    /// Register a body derived from `source` (stitched, filled, thickened,
    /// repaired): when `source` belongs to a component the
    /// new body takes its place in that definition (the source leaves it, so a
    /// hidden source is not exported or checked twice); otherwise the new body
    /// is unowned. The active component is not consulted.
    pub fn add_derived_body(&mut self, name: impl Into<String>, source: BodyId) -> BodyId {
        let id = self.add_body_unowned(name);
        if let Some(c) = self
            .assembly
            .components
            .iter_mut()
            .find(|c| c.bodies.contains(&source))
        {
            for b in &mut c.bodies {
                if *b == source {
                    *b = id;
                }
            }
        }
        id
    }

    /// Allocate a body id and register its metadata (`name` must be unique;
    /// see [`Document::default_body_name`]). While a component is active
    /// the new body joins its definition; display/derived bodies use
    /// [`Document::add_body_unowned`].
    pub fn add_body(&mut self, name: impl Into<String>) -> BodyId {
        let id = BodyId(self.next_body_id.clamp(1, u32::MAX - 1));
        self.next_body_id = id.0.saturating_add(1);
        self.bodies.push(BodyInfo {
            id,
            name: name.into(),
            visible: true,
            material: None,
        });
        // A body created while a component is active joins its
        // definition (docs/ASSEMBLIES.md, active-component editing).
        if let Some(c) = self.assembly.active
            && let Ok(c) = self.assembly.component_mut(c)
        {
            c.bodies.push(id);
        }
        id
    }

    pub fn body(&self, id: BodyId) -> Result<&BodyInfo> {
        self.bodies
            .iter()
            .find(|b| b.id == id)
            .ok_or_else(|| DocError::Validation(format!("unknown body {id}")))
    }

    pub fn body_mut(&mut self, id: BodyId) -> Result<&mut BodyInfo> {
        self.bodies
            .iter_mut()
            .find(|b| b.id == id)
            .ok_or_else(|| DocError::Validation(format!("unknown body {id}")))
    }

    /// Unique default body name like "Body1".
    pub fn default_body_name(&self) -> String {
        (1..)
            .map(|i| format!("Body{i}"))
            .find(|n| !self.bodies.iter().any(|b| &b.name == n))
            .unwrap_or_else(|| "Body".to_string())
    }

    /// Embed a source file; returns its id.
    pub fn add_blob(&mut self, file_name: &str, bytes: &[u8]) -> BlobId {
        let id = BlobId(self.next_blob_id.clamp(1, u32::MAX - 1));
        self.next_blob_id = id.0.saturating_add(1);
        self.blobs.push(Blob::new(id, file_name, bytes));
        id
    }

    pub fn blob(&self, id: BlobId) -> Result<&Blob> {
        self.blobs
            .iter()
            .find(|b| b.id == id)
            .ok_or_else(|| DocError::Validation(format!("unknown embedded file {id}")))
    }

    /// Feature that creates body `id`.
    pub fn body_creator(&self, id: BodyId) -> Option<FeatureId> {
        self.features
            .iter()
            .find(|f| f.created_bodies().contains(&id))
            .map(|f| f.id)
    }

    /// All features `f` depends on: explicit references plus the creator of
    /// its target body.
    pub fn dependencies_of(&self, f: &Feature) -> Vec<FeatureId> {
        let mut d = f.dependencies();
        if let Some(t) = f.target_body()
            && let Some(c) = self.body_creator(t)
            && !d.contains(&c)
        {
            d.push(c);
        }
        // A combine also reads its tool bodies.
        for t in f.tool_bodies() {
            if let Some(c) = self.body_creator(t)
                && !d.contains(&c)
            {
                d.push(c);
            }
        }
        d
    }

    /// Body that `f` modifies without creating it: a Join/Cut/Pocket target,
    /// the seed's target for patterns and mirrors, the faces' body for a
    /// chamfer.
    pub fn modified_body(&self, f: &Feature) -> Option<BodyId> {
        if let Some(t) = f.target_body() {
            return Some(t);
        }
        match &f.kind {
            FeatureKind::LinearPattern { seed, .. }
            | FeatureKind::CircularPattern { seed, .. }
            | FeatureKind::Mirror { seed, .. } => {
                self.feature(*seed).ok().and_then(Feature::target_body)
            }
            FeatureKind::Chamfer { a, .. } | FeatureKind::Fillet { a, .. } => self.face_body(a),
            FeatureKind::ShellFace { face, .. } | FeatureKind::AlignBody { from: face, .. } => {
                self.face_body(face)
            }
            FeatureKind::Shell { extrude, .. } => self
                .feature(*extrude)
                .ok()
                .and_then(|e| e.created_bodies().first().copied()),
            FeatureKind::Countersink { hole, .. } => {
                self.feature(*hole).ok().and_then(Feature::target_body)
            }
            _ => None,
        }
    }

    /// Body owning the face `r` names (from the definitions only).
    pub fn face_body(&self, r: &FaceRef) -> Option<BodyId> {
        self.face_body_depth(r, 0)
    }

    fn face_body_depth(&self, r: &FaceRef, depth: usize) -> Option<BodyId> {
        if depth > self.features.len() {
            return None; // a (malformed) reference loop
        }
        match r.role {
            FaceRole::Imported { body, .. } => Some(body),
            _ => {
                let f = self.feature(r.feature).ok()?;
                match &f.kind {
                    FeatureKind::LinearPattern { seed, .. }
                    | FeatureKind::CircularPattern { seed, .. }
                    | FeatureKind::Mirror { seed, .. } => {
                        return self.feature(*seed).ok()?.target_body();
                    }
                    FeatureKind::Chamfer { a, .. } | FeatureKind::Fillet { a, .. } => {
                        return self.face_body_depth(a, depth + 1);
                    }
                    _ => {}
                }
                match f.created_bodies().first() {
                    Some(b) => Some(*b),
                    None => f.target_body(),
                }
            }
        }
    }

    /// [`Document::dependencies_of`] plus the ordering constraint between
    /// features acting on the same body: a feature that modifies a body comes
    /// after the previous feature (in history) that created or modified it.
    /// Without this, re-attaching a sketch to a face of a later feature could
    /// silently swap two modifiers of one body; with it, that is a cycle and
    /// the edit is refused. Not used for deletion (deleting a modifier that
    /// nothing references is allowed).
    pub fn ordering_dependencies_of(&self, f: &Feature) -> Vec<FeatureId> {
        let mut d = self.dependencies_of(f);
        if let Some(b) = self.modified_body(f)
            && let Some(p) = self.features.iter().position(|x| x.id == f.id)
            && let Some(prev) = self.features[..p]
                .iter()
                .rev()
                .find(|x| x.created_bodies().contains(&b) || self.modified_body(x) == Some(b))
            && !d.contains(&prev.id)
        {
            d.push(prev.id);
        }
        d
    }

    /// Every evaluated feature's dependencies are evaluated: a feature that is
    /// not suppressed may not depend on a suppressed one.
    pub fn check_suppression(&self) -> Result<()> {
        if let Some(m) = self.rollback {
            self.feature(m).map_err(|_| {
                DocError::Validation(format!("the timeline marker names missing feature {m}"))
            })?;
        }
        for f in self
            .features
            .iter()
            .filter(|f| !f.suppressed && !self.is_rolled_back(f.id))
        {
            for d in self.dependencies_of(f) {
                if self.is_rolled_back(d) {
                    return Err(DocError::BrokenReference {
                        from: f.id,
                        detail: format!(
                            "{} ({}) depends on {d}, which is after the timeline marker; move \
                             the marker past {d}",
                            f.id, f.name
                        ),
                    });
                }
                if let Ok(g) = self.feature(d)
                    && g.suppressed
                {
                    return Err(DocError::BrokenReference {
                        from: f.id,
                        detail: format!(
                            "{} ({}) depends on {} ({}), which is suppressed; suppress {} too \
                             (with dependents) or restore {}",
                            f.id, f.name, g.id, g.name, f.id, g.id
                        ),
                    });
                }
            }
        }
        Ok(())
    }

    /// `id` and every feature that depends on it, directly or transitively
    /// (history order).
    pub fn with_dependents(&self, id: FeatureId) -> Vec<FeatureId> {
        let mut out = vec![id];
        let mut i = 0;
        while i < out.len() {
            for d in self.dependents_of(out[i]) {
                if !out.contains(&d) {
                    out.push(d);
                }
            }
            i += 1;
        }
        self.features
            .iter()
            .map(|f| f.id)
            .filter(|f| out.contains(f))
            .collect()
    }

    /// Features that depend on `id` (explicitly or through a body target).
    pub fn dependents_of(&self, id: FeatureId) -> Vec<FeatureId> {
        self.features
            .iter()
            .filter(|f| self.dependencies_of(f).contains(&id))
            .map(|f| f.id)
            .collect()
    }

    /// Consistency of bodies and blobs (ADR 0003): every body is created by
    /// exactly one feature and has exactly one metadata entry; targets name
    /// existing bodies; blob references resolve; unused blobs are removed by
    /// [`Document::prune_blobs`], so they are an error here.
    pub fn validate_bodies(&self) -> Result<()> {
        let mut created = std::collections::HashMap::new();
        for f in &self.features {
            for b in f.created_bodies() {
                if b.0 == 0 || b.0 >= self.next_body_id {
                    return Err(DocError::Validation(format!(
                        "{}: body id {b} is unassigned or >= next_body_id {}",
                        f.id, self.next_body_id
                    )));
                }
                if let Some(prev) = created.insert(b, f.id) {
                    return Err(DocError::Validation(format!(
                        "body {b} is created by both {prev} and {}",
                        f.id
                    )));
                }
            }
        }
        let mut seen = std::collections::HashSet::new();
        for info in &self.bodies {
            if !seen.insert(info.id) {
                return Err(DocError::Validation(format!(
                    "duplicate body entry {}",
                    info.id
                )));
            }
            if let Some(m) = &info.material {
                m.validate().map_err(|e| {
                    DocError::Validation(format!("body {} ({}): {e}", info.id, info.name))
                })?;
            }
            if !created.contains_key(&info.id) {
                return Err(DocError::Validation(format!(
                    "body {} ({}) is not created by any feature",
                    info.id, info.name
                )));
            }
        }
        for (b, f) in &created {
            if !seen.contains(b) {
                return Err(DocError::Validation(format!(
                    "{f}: body {b} has no body entry"
                )));
            }
        }
        for f in &self.features {
            if let Some(t) = f.target_body()
                && !created.contains_key(&t)
            {
                return Err(DocError::BrokenReference {
                    from: f.id,
                    detail: format!("target body {t} does not exist"),
                });
            }
            for t in f.tool_bodies() {
                if !created.contains_key(&t) {
                    return Err(DocError::BrokenReference {
                        from: f.id,
                        detail: format!("tool body {t} does not exist"),
                    });
                }
            }
            if let Some(b) = f.blob() {
                self.blob(b).map_err(|_| DocError::BrokenReference {
                    from: f.id,
                    detail: format!("embedded file {b} is missing"),
                })?;
            }
        }
        self.assembly.validate(&self.bodies)?;
        let mut blob_ids = std::collections::HashSet::new();
        for b in &self.blobs {
            if !blob_ids.insert(b.id) || b.id.0 == 0 || b.id.0 >= self.next_blob_id {
                return Err(DocError::Validation(format!("invalid blob id {}", b.id)));
            }
        }
        Ok(())
    }

    /// Drop embedded files no feature references (after deleting an import).
    pub fn prune_blobs(&mut self) {
        let used: std::collections::HashSet<BlobId> =
            self.features.iter().filter_map(Feature::blob).collect();
        self.blobs.retain(|b| used.contains(&b.id));
    }

    /// After deleting `removed`, a body it derived from a
    /// source (and that replaced the source in a component) gives the source
    /// its place back, so the component keeps its geometry. Call before
    /// [`Document::prune_bodies`].
    pub fn restore_derived_source(&mut self, removed: &Feature) {
        let Some((source, derived)) = removed.derived_body() else {
            return;
        };
        if self.body(source).is_err() {
            return;
        }
        for c in &mut self.assembly.components {
            if !c.bodies.contains(&derived) {
                continue;
            }
            if c.bodies.contains(&source) {
                c.bodies.retain(|b| *b != derived);
            } else {
                for b in &mut c.bodies {
                    if *b == derived {
                        *b = source;
                    }
                }
            }
        }
    }

    /// Drop body entries no feature creates (after deleting a body's creator).
    pub fn prune_bodies(&mut self) {
        let made: std::collections::HashSet<BodyId> = self
            .features
            .iter()
            .flat_map(Feature::created_bodies)
            .collect();
        self.bodies.retain(|b| made.contains(&b.id));
        // Component definitions drop the removed bodies too (a
        // component may become empty; its occurrences stay).
        for c in &mut self.assembly.components {
            c.bodies.retain(|b| made.contains(b));
        }
    }

    pub fn feature(&self, id: FeatureId) -> Result<&Feature> {
        self.features
            .iter()
            .find(|f| f.id == id)
            .ok_or(DocError::UnknownFeature(id))
    }

    pub fn feature_mut(&mut self, id: FeatureId) -> Result<&mut Feature> {
        self.features
            .iter_mut()
            .find(|f| f.id == id)
            .ok_or(DocError::UnknownFeature(id))
    }

    /// Append a feature, allocating its id. Ids saturate at `u32::MAX - 1`; at that
    /// point `evaluation_order` rejects the document instead of wrapping.
    pub fn push(&mut self, name: impl Into<String>, kind: FeatureKind) -> FeatureId {
        let id = FeatureId(self.next_id.clamp(1, u32::MAX - 1));
        self.next_id = id.0.saturating_add(1);
        let f = Feature {
            id,
            name: name.into(),
            kind,
            notes: vec![],
            expressions: Default::default(),
            suppressed: false,
        };
        // With the timeline rolled back, insert at the marker and move it.
        match self
            .rollback
            .and_then(|m| self.features.iter().position(|x| x.id == m))
        {
            Some(p) => {
                self.features.insert(p + 1, f);
                self.rollback = Some(id);
            }
            None => self.features.push(f),
        }
        id
    }

    /// Whether `id` lies after the timeline marker (rolled back).
    pub fn is_rolled_back(&self, id: FeatureId) -> bool {
        let pos = |x: FeatureId| self.features.iter().position(|f| f.id == x);
        match (self.rollback.and_then(pos), pos(id)) {
            (Some(m), Some(p)) => p > m,
            _ => false,
        }
    }

    /// Move the timeline marker after `at` (None: to the end). The marker at
    /// the last feature is stored as None.
    pub fn set_rollback(&mut self, at: Option<FeatureId>) -> Result<()> {
        if let Some(a) = at {
            self.feature(a)?;
        }
        self.rollback = at.filter(|a| self.features.last().map(|f| f.id) != Some(*a));
        Ok(())
    }

    /// Reorder: move `id` before `before` (None: to the end of history).
    /// Allowed only when every feature it depends on stays before it and every
    /// feature depending on it stays after it (`dependencies_of`, face and
    /// plane references, patterns' seeds); regeneration then decides whether
    /// the new order of operations on a body still builds. Refused otherwise
    /// with the blocking feature named.
    pub fn move_feature(&mut self, id: FeatureId, before: Option<FeatureId>) -> Result<()> {
        if before == Some(id) {
            return Ok(());
        }
        let from = self
            .features
            .iter()
            .position(|f| f.id == id)
            .ok_or(DocError::UnknownFeature(id))?;
        let f = self.features.remove(from);
        let to = match before {
            Some(b) => self
                .features
                .iter()
                .position(|x| x.id == b)
                .ok_or(DocError::UnknownFeature(b))?,
            None => self.features.len(),
        };
        self.features.insert(to, f);
        let pos = |x: FeatureId| self.features.iter().position(|g| g.id == x);
        let me = self.feature(id)?.clone();
        for d in self.dependencies_of(&me) {
            if pos(d).is_some_and(|p| p > to) {
                let g = self.feature(d)?;
                return Err(DocError::Validation(format!(
                    "{id} ({}) cannot move before {d} ({}), which it depends on",
                    me.name, g.name
                )));
            }
        }
        for u in self.dependents_of(id) {
            if pos(u).is_some_and(|p| p < to) {
                let g = self.feature(u)?;
                return Err(DocError::Validation(format!(
                    "{id} ({}) cannot move after {u} ({}), which depends on it",
                    me.name, g.name
                )));
            }
        }
        // A body must be created before anything that modifies it.
        if let Some(b) = self.modified_body(&me) {
            let creator = self
                .features
                .iter()
                .position(|x| x.created_bodies().contains(&b));
            if creator.is_some_and(|c| c > to) {
                return Err(DocError::Validation(format!(
                    "{id} ({}) cannot move before the feature that creates {b}",
                    me.name
                )));
            }
        }
        for b in me.created_bodies() {
            if let Some(u) = self
                .features
                .iter()
                .take(to)
                .find(|x| self.modified_body(x) == Some(b))
            {
                return Err(DocError::Validation(format!(
                    "{id} ({}) creates {b}; it cannot move after {} ({}), which modifies it",
                    me.name, u.id, u.name
                )));
            }
        }
        Ok(())
    }

    /// Append a new-body distance extrusion of `sketch`, allocating its body
    /// (default name). Convenience for the common case.
    pub fn push_extrude(
        &mut self,
        name: impl Into<String>,
        sketch: FeatureId,
        distance: f64,
    ) -> FeatureId {
        let body = self.add_body(self.default_body_name());
        self.push(
            name,
            FeatureKind::extrude(sketch, distance, Operation::NewBody { body }),
        )
    }

    /// Unique default name like "Sketch1".
    pub fn default_name(&self, prefix: &str) -> String {
        (1..)
            .map(|i| format!("{prefix}{i}"))
            .find(|n| !self.features.iter().any(|f| &f.name == n))
            .unwrap_or_else(|| prefix.to_string())
    }

    /// Feature ids in a valid evaluation order (Kahn's algorithm, ties broken by
    /// history position for determinism). Errors on unknown ids or cycles.
    pub fn evaluation_order(&self) -> Result<Vec<FeatureId>> {
        let n = self.features.len();
        let pos = |id: FeatureId| self.features.iter().position(|f| f.id == id);
        let mut seen = std::collections::HashSet::new();
        for f in &self.features {
            if !seen.insert(f.id) {
                return Err(DocError::Validation(format!(
                    "duplicate feature id {}",
                    f.id
                )));
            }
            if f.id.0 >= self.next_id {
                return Err(DocError::Validation(format!(
                    "feature id {} >= next_id {}",
                    f.id, self.next_id
                )));
            }
        }
        let mut indeg = vec![0usize; n];
        let mut users: Vec<Vec<usize>> = vec![Vec::new(); n];
        for (i, f) in self.features.iter().enumerate() {
            for d in self.ordering_dependencies_of(f) {
                let j = pos(d).ok_or(DocError::BrokenReference {
                    from: f.id,
                    detail: format!("depends on missing feature {d}"),
                })?;
                indeg[i] += 1;
                users[j].push(i);
            }
        }
        let mut ready: std::collections::BTreeSet<usize> =
            (0..n).filter(|&i| indeg[i] == 0).collect();
        let mut order = Vec::with_capacity(n);
        while let Some(i) = ready.pop_first() {
            order.push(self.features[i].id);
            for &u in &users[i] {
                indeg[u] -= 1;
                if indeg[u] == 0 {
                    ready.insert(u);
                }
            }
        }
        if order.len() != n {
            let stuck = (0..n)
                .filter(|&i| indeg[i] > 0)
                .map(|i| self.features[i].id)
                .collect();
            return Err(DocError::Cycle(stuck));
        }
        Ok(order)
    }
}
