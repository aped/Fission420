/// Stable feature identifier. Allocated monotonically, never reused.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct FeatureId(pub u32);

impl fmt::Display for FeatureId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "F{}", self.0)
    }
}

/// Stable body identifier (ADR 0003). Allocated monotonically from
/// [`Document::next_body_id`], stored in the creating feature, never reused.
/// `BodyId(0)` means "unassigned" and only exists transiently while migrating
/// v1/v2 files.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, Default,
)]
pub struct BodyId(pub u32);

impl fmt::Display for BodyId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "B{}", self.0)
    }
}

/// User-facing body metadata. Geometry comes from the creating feature.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BodyInfo {
    pub id: BodyId,
    pub name: String,
    #[serde(default = "yes")]
    pub visible: bool,
}

fn yes() -> bool {
    true
}

/// Identifier of an embedded binary/text blob (imported source files).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct BlobId(pub u32);

impl fmt::Display for BlobId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "blob{}", self.0)
    }
}

/// An embedded source file (immutable once added). The native document keeps
/// the bytes so it never depends on the original path (ADR 0003).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Blob {
    pub id: BlobId,
    /// Original file name (provenance only; never reopened).
    pub file_name: String,
    /// Size of the decoded bytes.
    pub len: u64,
    /// FNV-1a 64 of the decoded bytes, hex (integrity check, not security).
    pub fnv64: String,
    /// The bytes: UTF-8 text verbatim, or base64.
    pub encoding: BlobEncoding,
    pub data: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum BlobEncoding {
    Text,
    Base64,
}

impl Blob {
    /// Embed `bytes` (stored as text when they are valid UTF-8, else base64).
    pub fn new(id: BlobId, file_name: &str, bytes: &[u8]) -> Self {
        let (encoding, data) = match std::str::from_utf8(bytes) {
            Ok(t) => (BlobEncoding::Text, t.to_string()),
            Err(_) => (BlobEncoding::Base64, crate::blob::base64_encode(bytes)),
        };
        Self {
            id,
            file_name: file_name.to_string(),
            len: bytes.len() as u64,
            fnv64: crate::blob::fnv64_hex(bytes),
            encoding,
            data,
        }
    }

    /// Decoded bytes, verified against the stored length and hash.
    pub fn bytes(&self) -> Result<Vec<u8>> {
        let b = match self.encoding {
            BlobEncoding::Text => self.data.as_bytes().to_vec(),
            BlobEncoding::Base64 => crate::blob::base64_decode(&self.data)
                .ok_or_else(|| DocError::File(format!("{}: invalid base64 data", self.id)))?,
        };
        if b.len() as u64 != self.len || crate::blob::fnv64_hex(&b) != self.fnv64 {
            return Err(DocError::File(format!(
                "{} ({}): embedded data is corrupt (length/hash mismatch)",
                self.id, self.file_name
            )));
        }
        Ok(b)
    }
}

/// Semantic role of a face generated by a feature. Resolved from the generating
/// feature's definition, then validated against the B-rep; never a face index.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum FaceRole {
    /// Planar cap at the end of an extrusion (the "top" for +Z extrusions). For a
    /// blind cut: the floor, outward normal pointing back toward the opening.
    ExtrudeEndCap,
    /// Planar cap at the start of an extrusion (on the profile plane).
    ExtrudeStartCap,
    /// Planar side face generated by profile line `entity` (sketch entity id) of an
    /// extrusion (New/Join: outer wall; Cut: wall of the removed region).
    ExtrudeSide { entity: u32 },
    /// Face `face` (stable import index: position in the solid's face order
    /// right after import) of imported body `body`. Sketches and other plane
    /// users accept planar faces only; direct edits (run 6,
    /// [`FeatureKind::DirectEdit`]) also name cylindrical faces this way.
    Imported { body: BodyId, face: u32 },
    /// Face of an occurrence made by a pattern or mirror feature (run 5): the
    /// face that seed tool `tool` (0 for an extrusion; a Hole: 0 = counterbore
    /// when present, then the hole) generates at occurrence `instance` (pattern:
    /// 1..count-1, the seed is occurrence 0 and keeps its own references;
    /// mirror: 1). The identity survives count changes; an occurrence that no
    /// longer exists is a `BrokenReference`, never another occurrence.
    Copy {
        instance: u32,
        #[serde(default)]
        tool: u32,
        of: CopiedRole,
    },
    /// The planar face made by a Chamfer feature (run 5).
    Chamfer,
}

/// Role of a seed tool's face within a pattern/mirror occurrence
/// ([`FaceRole::Copy`]); same meaning as the extrusion roles.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum CopiedRole {
    EndCap,
    StartCap,
    Side { entity: u32 },
}

impl CopiedRole {
    /// The equivalent extrusion role (on the occurrence's own tool).
    pub fn extrude_role(self) -> FaceRole {
        match self {
            CopiedRole::EndCap => FaceRole::ExtrudeEndCap,
            CopiedRole::StartCap => FaceRole::ExtrudeStartCap,
            CopiedRole::Side { entity } => FaceRole::ExtrudeSide { entity },
        }
    }
}

/// Persistent face selection: originating feature + generated-face role.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct FaceRef {
    pub feature: FeatureId,
    pub role: FaceRole,
}

#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub enum SketchPlane {
    /// World XY plane through the origin, normal +Z.
    WorldXY,
    /// World XZ plane through the origin: local x = world X, local y = world Z, normal -Y.
    WorldXZ,
    /// World YZ plane through the origin: local x = world Y, local y = world Z, normal +X.
    WorldYZ,
    /// A planar face generated by an earlier feature.
    Face(FaceRef),
    /// Construction plane (run 4): `base` moved `distance` mm along its normal
    /// (a face's outward normal; +Z / −Y / +X for the world planes), same
    /// in-plane axes. Parameter "plane_offset" of the sketch (bindable). A
    /// face base resolves like `Face` (BrokenReference when it is gone).
    /// Run 5: `angle` (radians, default 0, written only when non-zero) first
    /// tilts the base plane about its local X axis through its origin
    /// (right-handed: +angle turns local +Y toward the normal), then the offset
    /// is applied along the tilted normal. Parameter "plane_angle_deg".
    Offset {
        base: PlaneBase,
        distance: f64,
        #[serde(default, skip_serializing_if = "is_zero")]
        angle: f64,
    },
}

fn is_zero(v: &f64) -> bool {
    *v == 0.0
}

// `distance` is validated finite wherever a plane is accepted, so equality is
// reflexive in practice.
impl Eq for SketchPlane {}

/// Base of an offset construction plane.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum PlaneBase {
    WorldXY,
    WorldXZ,
    WorldYZ,
    Face(FaceRef),
}

impl PlaneBase {
    /// The base as a plain sketch plane.
    pub fn plane(self) -> SketchPlane {
        match self {
            PlaneBase::WorldXY => SketchPlane::WorldXY,
            PlaneBase::WorldXZ => SketchPlane::WorldXZ,
            PlaneBase::WorldYZ => SketchPlane::WorldYZ,
            PlaneBase::Face(r) => SketchPlane::Face(r),
        }
    }
}

impl SketchPlane {
    /// The face this plane is on or offset from, if any.
    pub fn face(&self) -> Option<FaceRef> {
        match *self {
            SketchPlane::Face(r)
            | SketchPlane::Offset {
                base: PlaneBase::Face(r),
                ..
            } => Some(r),
            _ => None,
        }
    }

    /// `(base plane, offset)`: an offset plane's base and distance, else
    /// `(self, 0)`.
    pub fn base_and_offset(&self) -> (SketchPlane, f64) {
        match *self {
            SketchPlane::Offset { base, distance, .. } => (base.plane(), distance),
            p => (p, 0.0),
        }
    }

    /// Tilt (radians) of a construction plane about its base's local X axis.
    pub fn angle(&self) -> f64 {
        match *self {
            SketchPlane::Offset { angle, .. } => angle,
            _ => 0.0,
        }
    }
}

/// What an extrusion does with its tool body (ADR 0003).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Operation {
    /// Create body `body`.
    NewBody { body: BodyId },
    /// Union the tool into `target`.
    Join { target: BodyId },
    /// Subtract the tool from `target`.
    Cut { target: BodyId },
}

impl Default for Operation {
    /// v1/v2 extrusions created the (single) base body; the id is assigned by migration.
    fn default() -> Self {
        Operation::NewBody { body: BodyId(0) }
    }
}

/// How far an extrusion goes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Extent {
    /// `distance` mm along the direction.
    #[default]
    Distance,
    /// Cut only: through all material of the target on both sides of the sketch
    /// plane along its normal (cutter length derived from the target's extent).
    ThroughAll,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum CutExtent {
    /// Through all material, both directions along the sketch normal.
    ThroughAll,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum FeatureKind {
    Sketch {
        plane: SketchPlane,
        sketch: Sketch,
    },
    /// New-body revolve of a sketch profile about the sketch's local Y axis.
    /// `angle` is in radians (exposed as parameter `angle_deg`).
    Revolve {
        sketch: FeatureId,
        angle: f64,
        /// Body created (v3; assigned by migration for older files).
        #[serde(default)]
        body: BodyId,
    },
    /// Extrusion of a sketch profile along the sketch normal (or against it when
    /// `reverse`): a new body, or joined to / cut from an explicit target body.
    Extrude {
        sketch: FeatureId,
        distance: f64,
        #[serde(default)]
        operation: Operation,
        #[serde(default)]
        extent: Extent,
        #[serde(default)]
        reverse: bool,
        /// Extrude only this bounded region of the sketch (run 4, additive:
        /// absent = the whole profile, exactly as before). Resolved by identity
        /// at every regeneration; a region that no longer exists is a
        /// `BrokenReference`, never another region.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        region: Option<rcad_sketch::RegionRef>,
    },
    /// Legacy (v1/v2) circular through-all cut; see [`FeatureKind::Extrude`] with
    /// [`Operation::Cut`] for general cuts.
    Cut {
        sketch: FeatureId,
        extent: CutExtent,
        #[serde(default)]
        target: BodyId,
    },
    /// Blind cut: removes the sketch profile from the sketched extrusion cap
    /// inward (against the cap's outward normal) to `depth` mm. Product limits:
    /// circular profile sketched on an end/start cap of the base extrusion,
    /// strictly inside it, 0 < depth < extrusion thickness (a through hole is
    /// `Cut`). Added in format v2; absent from v1 files.
    Pocket {
        sketch: FeatureId,
        depth: f64,
        #[serde(default)]
        target: BodyId,
    },
    /// Base feature: exact solids imported from an embedded STEP file. One body
    /// per imported solid (in file order). No source feature history.
    ImportStep {
        blob: BlobId,
        /// Unit scale used when the file declares no length unit (mm per unit).
        #[serde(default)]
        unit_override_to_mm: Option<f64>,
        bodies: Vec<BodyId>,
    },
    /// Base feature: a triangle mesh (STL) body, scaled by `to_mm` (STL is unitless).
    ImportMesh {
        blob: BlobId,
        to_mm: f64,
        body: BodyId,
    },
    /// Base feature: mesh bodies from an embedded 3MF package, one per build item
    /// in file order (units declared by the file).
    Import3mf {
        blob: BlobId,
        bodies: Vec<BodyId>,
    },
    /// Repeat the tool of `seed` (an Extrude Join/Cut or a Hole) `count - 1` more
    /// times (count 1 = the seed only, no copies; run 5), each
    /// shifted by `spacing` mm along `direction` (seed sketch-plane coordinates,
    /// normalized), on the seed's target body. The seed is instance 0.
    LinearPattern {
        seed: FeatureId,
        count: u32,
        spacing: f64,
        direction: [f64; 2],
    },
    /// Apply the reflection of `seed`'s tool (an Extrude Join or Cut) across
    /// `plane` (a world plane through the origin or a planar face) to the seed's
    /// target body. The seed itself stays; this adds the mirrored copy.
    Mirror {
        seed: FeatureId,
        plane: SketchPlane,
    },
    /// Repeat the tool of `seed` (an Extrude Join/Cut) `count - 1` more times,
    /// each rotated by a further `angle` (radians; parameter `angle_deg`, counter-
    /// clockwise about the seed sketch's normal) about `center` (seed sketch-plane
    /// coordinates), on the seed's target body. The seed is instance 0.
    CircularPattern {
        seed: FeatureId,
        count: u32,
        angle: f64,
        center: [f64; 2],
    },
    /// Equal-distance chamfer of the straight convex edge where planar faces `a`
    /// and `b` (semantic references on one body) meet, `distance` mm along each.
    Chamfer {
        a: FaceRef,
        b: FaceRef,
        distance: f64,
    },
    /// Exact solid fillet (run 5) of the straight convex edge where planar
    /// faces `a` and `b` meet: an exact cylinder of `radius` mm tangent to
    /// both. Scope (`rcad_kernel::fillet_edge`): the body is prismatic along
    /// the edge (planar faces parallel/perpendicular to it), end faces
    /// perpendicular; refused otherwise with the reason. Parameter "radius".
    Fillet {
        a: FaceRef,
        b: FaceRef,
        radius: f64,
    },
    /// Exact loft (run 5, ADR 0008) between the closed profiles of sketches
    /// `a` and `b` on parallel planes, as new body `body`: equal-count
    /// polygons whose corresponding edges are parallel (planar sides; vertex
    /// correspondence by the rule in ADR 0008), or two coaxial circles (cone
    /// frustum). Anything else is refused with the reason.
    Loft {
        a: FeatureId,
        b: FeatureId,
        body: BodyId,
    },
    /// Exact sweep (run 5, ADR 0009) of the closed profile of sketch `profile`
    /// along the open chain of lines and arcs of sketch `path`, as new body
    /// `body`. The path starts at the profile sketch's origin, leaving along
    /// its normal; joints tangent; planar path. Refused otherwise by name.
    Sweep {
        profile: FeatureId,
        path: FeatureId,
        body: BodyId,
    },
    /// Round hole (run 4) drilled into `target` from `plane` (which must hold a
    /// planar face of the target; the hole goes into the material), centred at
    /// `center` (plane coordinates): `diameter`, `depth` mm from the face
    /// (`None`: through all), and an optional counterbore. Parameters
    /// "diameter", "depth", "cbore_diameter", "cbore_depth", "center_x",
    /// "center_y". Built as a counterbore cut then the hole cut, each checked
    /// like an Extrude Cut (ADR 0005). Countersinks are not supported.
    Hole {
        plane: SketchPlane,
        center: [f64; 2],
        diameter: f64,
        #[serde(default)]
        depth: Option<f64>,
        #[serde(default)]
        counterbore: Option<Counterbore>,
        target: BodyId,
    },
    /// Scoped shell (run 4; docs/SHELL.md): hollows the body of `extrude` (a New
    /// Body extrusion of a single closed loop of lines/arcs or a circle, no
    /// holes, no picked region) leaving walls and a floor `thickness` mm thick,
    /// open at the `open` cap (`ExtrudeEndCap` or `ExtrudeStartCap`). Built as a
    /// blind cut of the profile offset inward by `thickness`, from the open cap
    /// to `distance − thickness` deep, checked like an Extrude Cut (ADR 0005).
    /// Not a general shell: other faces and later features are not offset.
    /// Parameter "thickness".
    Shell {
        extrude: FeatureId,
        open: FaceRole,
        thickness: f64,
    },
    /// Direct edit (run 6, ADR 0010) of an imported STEP body: `face` is an
    /// imported face (`FaceRole::Imported`, by stable import index) and `op`
    /// what is done to it, exactly (`rcad_kernel::{offset_face,
    /// resize_cylinder, remove_cylinder}`). This is direct-edit history, not
    /// recovered feature history (STEP has none). Applies only while the body
    /// has been changed by nothing but its import and direct edits; a face
    /// removed by an earlier edit is a `BrokenReference`.
    DirectEdit {
        face: FaceRef,
        op: DirectOp,
    },
}

/// Edit of a [`FeatureKind::DirectEdit`] (run 6, ADR 0010).
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub enum DirectOp {
    /// Move the planar face along its outward normal by `distance` mm
    /// (positive adds material). Parameter "distance".
    OffsetFace { distance: f64 },
    /// Set the diameter of the hole or boss whose cylindrical wall is the
    /// face. Parameter "diameter".
    ResizeCylinder { diameter: f64 },
    /// Delete the hole or boss whose cylindrical wall is the face and close
    /// the openings it leaves.
    RemoveCylinder,
}

/// Counterbore of a [`FeatureKind::Hole`]: a coaxial larger blind cut.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct Counterbore {
    pub diameter: f64,
    pub depth: f64,
}

impl FeatureKind {
    /// Distance extrusion along the sketch normal.
    pub fn extrude(sketch: FeatureId, distance: f64, operation: Operation) -> Self {
        FeatureKind::Extrude {
            sketch,
            distance,
            operation,
            extent: Extent::Distance,
            reverse: false,
            region: None,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Feature {
    pub id: FeatureId,
    pub name: String,
    pub kind: FeatureKind,
    /// Provenance notes kept with the definition (e.g. DXF/SVG import units,
    /// counts and skipped content). Informational; never affects geometry.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub notes: Vec<String>,
    /// Editable parameters bound to expressions (parameter name -> expression
    /// text, v4; see `params.rs`). The bound values in `kind` are derived from
    /// these by every transaction.
    #[serde(default, skip_serializing_if = "std::collections::BTreeMap::is_empty")]
    pub expressions: std::collections::BTreeMap<String, String>,
    /// Suppressed (run 5): kept in history, not evaluated. Nothing that is
    /// evaluated may depend on a suppressed feature
    /// ([`Document::check_suppression`]): dependents are suppressed with it or
    /// the change is refused, never silently rebound. Serde-additive.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub suppressed: bool,
}

impl Feature {
    /// Features this one depends on.
    pub fn dependencies(&self) -> Vec<FeatureId> {
        match &self.kind {
            FeatureKind::Sketch { plane, .. } => {
                plane.face().map(|r| r.feature).into_iter().collect()
            }
            FeatureKind::Extrude { sketch, .. }
            | FeatureKind::Cut { sketch, .. }
            | FeatureKind::Pocket { sketch, .. }
            | FeatureKind::Revolve { sketch, .. } => vec![*sketch],
            FeatureKind::Loft { a, b, .. } => vec![*a, *b],
            FeatureKind::Sweep { profile, path, .. } => vec![*profile, *path],
            FeatureKind::LinearPattern { seed, .. } | FeatureKind::CircularPattern { seed, .. } => {
                vec![*seed]
            }
            FeatureKind::Mirror { seed, plane } => std::iter::once(*seed)
                .chain(plane.face().map(|r| r.feature))
                .collect(),
            FeatureKind::Chamfer { a, b, .. } | FeatureKind::Fillet { a, b, .. } => {
                let mut v = vec![a.feature];
                if b.feature != a.feature {
                    v.push(b.feature);
                }
                v
            }
            FeatureKind::Hole { plane, .. } => {
                plane.face().map(|r| r.feature).into_iter().collect()
            }
            FeatureKind::Shell { extrude, .. } => vec![*extrude],
            FeatureKind::DirectEdit { face, .. } => vec![face.feature],
            FeatureKind::ImportStep { .. }
            | FeatureKind::ImportMesh { .. }
            | FeatureKind::Import3mf { .. } => vec![],
        }
    }

    /// Bodies this feature creates.
    pub fn created_bodies(&self) -> Vec<BodyId> {
        match &self.kind {
            FeatureKind::Extrude {
                operation: Operation::NewBody { body },
                ..
            }
            | FeatureKind::Revolve { body, .. }
            | FeatureKind::Loft { body, .. }
            | FeatureKind::Sweep { body, .. }
            | FeatureKind::ImportMesh { body, .. } => vec![*body],
            FeatureKind::ImportStep { bodies, .. } | FeatureKind::Import3mf { bodies, .. } => {
                bodies.clone()
            }
            _ => vec![],
        }
    }

    /// Body this feature modifies (Join/Cut target), if any.
    pub fn target_body(&self) -> Option<BodyId> {
        match &self.kind {
            FeatureKind::Extrude {
                operation: Operation::Join { target } | Operation::Cut { target },
                ..
            }
            | FeatureKind::Cut { target, .. }
            | FeatureKind::Pocket { target, .. }
            | FeatureKind::Hole { target, .. } => Some(*target),
            FeatureKind::DirectEdit {
                face:
                    FaceRef {
                        role: FaceRole::Imported { body, .. },
                        ..
                    },
                ..
            } => Some(*body),
            _ => None,
        }
    }

    /// Embedded blob this feature reads, if any.
    pub fn blob(&self) -> Option<BlobId> {
        match &self.kind {
            FeatureKind::ImportStep { blob, .. }
            | FeatureKind::ImportMesh { blob, .. }
            | FeatureKind::Import3mf { blob, .. } => Some(*blob),
            _ => None,
        }
    }

    /// Editable named parameters (mm).
    pub fn parameters(&self) -> Vec<(String, f64)> {
        match &self.kind {
            FeatureKind::Sketch { sketch, plane } => {
                let mut p = sketch.dimensions();
                if let Some((x, y)) = anchor(sketch) {
                    p.push(("center_x".into(), x));
                    p.push(("center_y".into(), y));
                }
                if let SketchPlane::Offset {
                    distance, angle, ..
                } = plane
                {
                    p.push(("plane_offset".into(), *distance));
                    p.push(("plane_angle_deg".into(), angle.to_degrees()));
                }
                p
            }
            // Unit conversion boundary: degrees for users, radians internally.
            FeatureKind::Revolve { angle, .. } => vec![("angle_deg".into(), angle.to_degrees())],
            FeatureKind::Extrude {
                extent: Extent::ThroughAll,
                ..
            } => vec![],
            FeatureKind::Extrude { distance, .. } => vec![("distance".into(), *distance)],
            // Run 5: an offset mirror plane's distance is a parameter.
            FeatureKind::Mirror {
                plane:
                    SketchPlane::Offset {
                        distance, angle, ..
                    },
                ..
            } => vec![
                ("plane_offset".into(), *distance),
                ("plane_angle_deg".into(), angle.to_degrees()),
            ],
            FeatureKind::Cut { .. }
            | FeatureKind::ImportStep { .. }
            | FeatureKind::Mirror { .. } => {
                vec![]
            }
            FeatureKind::ImportMesh { .. } | FeatureKind::Import3mf { .. } => vec![],
            FeatureKind::Loft { .. } | FeatureKind::Sweep { .. } => vec![],
            FeatureKind::Pocket { depth, .. } => vec![("depth".into(), *depth)],
            FeatureKind::Chamfer { distance, .. } => vec![("distance".into(), *distance)],
            FeatureKind::Fillet { radius, .. } => vec![("radius".into(), *radius)],
            FeatureKind::Shell { thickness, .. } => vec![("thickness".into(), *thickness)],
            FeatureKind::DirectEdit { op, .. } => match op {
                DirectOp::OffsetFace { distance } => vec![("distance".into(), *distance)],
                DirectOp::ResizeCylinder { diameter } => vec![("diameter".into(), *diameter)],
                DirectOp::RemoveCylinder => vec![],
            },
            FeatureKind::Hole {
                center,
                diameter,
                depth,
                counterbore,
                plane,
                ..
            } => {
                let mut v = vec![("diameter".into(), *diameter)];
                if let Some(d) = depth {
                    v.push(("depth".into(), *d));
                }
                if let Some(c) = counterbore {
                    v.push(("cbore_diameter".into(), c.diameter));
                    v.push(("cbore_depth".into(), c.depth));
                }
                v.push(("center_x".into(), center[0]));
                v.push(("center_y".into(), center[1]));
                if let SketchPlane::Offset {
                    distance, angle, ..
                } = plane
                {
                    v.push(("plane_offset".into(), *distance));
                    v.push(("plane_angle_deg".into(), angle.to_degrees()));
                }
                v
            }
            FeatureKind::LinearPattern { count, spacing, .. } => vec![
                ("count".into(), f64::from(*count)),
                ("spacing".into(), *spacing),
            ],
            FeatureKind::CircularPattern { count, angle, .. } => vec![
                ("count".into(), f64::from(*count)),
                ("angle_deg".into(), angle.to_degrees()),
            ],
        }
    }

    /// Set several parameters at once; on error the feature is unchanged and
    /// the failing slot is named. Hole sizes are validated in their final
    /// combination (a depth and its counterbore depth may change together).
    pub fn set_parameters(
        &mut self,
        values: &[(String, f64)],
    ) -> std::result::Result<(), (String, DocError)> {
        let mut trial = self.clone();
        if let FeatureKind::Hole {
            center,
            diameter,
            depth,
            counterbore,
            plane,
            ..
        } = &mut trial.kind
        {
            for (n, v) in values {
                match (n.as_str(), counterbore.as_mut(), depth.as_mut()) {
                    ("plane_offset", ..) if matches!(plane, SketchPlane::Offset { .. }) => {
                        if let SketchPlane::Offset { distance, .. } = plane {
                            *distance = *v;
                        }
                    }
                    ("plane_angle_deg", ..) if matches!(plane, SketchPlane::Offset { .. }) => {
                        if let SketchPlane::Offset { angle, .. } = plane {
                            *angle = v.to_radians();
                        }
                    }
                    ("diameter", ..) => *diameter = *v,
                    ("depth", _, Some(d)) => *d = *v,
                    ("cbore_diameter", Some(c), _) => c.diameter = *v,
                    ("cbore_depth", Some(c), _) => c.depth = *v,
                    ("center_x", ..) => center[0] = *v,
                    ("center_y", ..) => center[1] = *v,
                    _ => {
                        return Err((
                            n.clone(),
                            DocError::UnknownParameter {
                                feature: self.id,
                                name: n.clone(),
                            },
                        ));
                    }
                }
            }
            // Validate the final combination: re-setting each value checks it
            // against its (final) partners.
            for (n, v) in values {
                trial
                    .clone()
                    .set_parameter(n, *v)
                    .map_err(|e| (n.clone(), e))?;
            }
        } else {
            for (n, v) in values {
                trial.set_parameter(n, *v).map_err(|e| (n.clone(), e))?;
            }
        }
        *self = trial;
        Ok(())
    }

    /// Set a parameter on the definition only (no regeneration).
    pub fn set_parameter(&mut self, name: &str, value: f64) -> Result<()> {
        let id = self.id;
        if !value.is_finite() {
            return Err(DocError::Validation(format!(
                "{id}.{name}: value must be finite, got {value}"
            )));
        }
        match &mut self.kind {
            // Only template sketches (exactly one fixed anchor, no origin) expose
            // center_x / center_y; on editor sketches the only FixedPoint is the
            // origin, which must never move.
            FeatureKind::Sketch { sketch, .. }
                if (name == "center_x" || name == "center_y") && anchor(sketch).is_some() =>
            {
                let Some(rcad_sketch::Constraint::FixedPoint { x, y, .. }) = sketch
                    .constraints
                    .iter_mut()
                    .find(|c| matches!(c, rcad_sketch::Constraint::FixedPoint { .. }))
                else {
                    return Err(DocError::UnknownParameter {
                        feature: id,
                        name: name.into(),
                    });
                };
                *(if name == "center_x" { x } else { y }) = value;
                Ok(())
            }
            FeatureKind::Sketch {
                plane: SketchPlane::Offset { angle, .. },
                ..
            }
            | FeatureKind::Mirror {
                plane: SketchPlane::Offset { angle, .. },
                ..
            }
            | FeatureKind::Hole {
                plane: SketchPlane::Offset { angle, .. },
                ..
            } if name == "plane_angle_deg" => {
                if !(value.is_finite() && value.abs() < 180.0) {
                    return Err(DocError::Validation(format!(
                        "{id}.plane_angle_deg: the plane angle must be in (-180, 180) degrees, \
                         got {value}"
                    )));
                }
                *angle = value.to_radians();
                Ok(())
            }
            FeatureKind::Sketch {
                plane: SketchPlane::Offset { distance, .. },
                ..
            }
            | FeatureKind::Mirror {
                plane: SketchPlane::Offset { distance, .. },
                ..
            }
            | FeatureKind::Hole {
                plane: SketchPlane::Offset { distance, .. },
                ..
            } if name == "plane_offset" => {
                if !value.is_finite() {
                    return Err(DocError::Validation(format!(
                        "{id}.plane_offset: the plane offset must be finite, got {value}"
                    )));
                }
                *distance = value;
                Ok(())
            }
            FeatureKind::Sketch { sketch, .. } => {
                sketch.set_dimension(name, value).map_err(|e| match e {
                    rcad_sketch::SketchError::UnknownDimension(_) => DocError::UnknownParameter {
                        feature: id,
                        name: name.into(),
                    },
                    other => DocError::Validation(format!("{id}.{name}: {other}")),
                })?;
                // Store the solved geometry so the definition stays a solved state
                // (freeform vertices are solver unknowns seeded from storage). A
                // failed solve leaves the seed; regeneration then reports it.
                let mut solved = sketch.clone();
                if solved.solve().is_success() {
                    *sketch = solved;
                }
                Ok(())
            }
            FeatureKind::Revolve { angle, .. } if name == "angle_deg" => {
                if value <= 0.0 || value > 360.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.angle_deg: revolve angle must be in (0, 360] degrees, got {value}"
                    )));
                }
                *angle = value.to_radians();
                Ok(())
            }
            FeatureKind::Extrude {
                distance, extent, ..
            } if name == "distance" && *extent == Extent::Distance => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.distance: extrusion thickness must be > 0 mm, got {value}"
                    )));
                }
                *distance = value;
                Ok(())
            }
            FeatureKind::LinearPattern { count, .. }
            | FeatureKind::CircularPattern { count, .. }
                if name == "count" =>
            {
                if value.fract() != 0.0 || !(1.0..=MAX_PATTERN_COUNT as f64).contains(&value) {
                    return Err(DocError::Validation(format!(
                        "{id}.count: pattern count must be an integer in 1..={MAX_PATTERN_COUNT} \
                         (1 = the seed only), got {value}"
                    )));
                }
                *count = value as u32;
                Ok(())
            }
            FeatureKind::CircularPattern { angle, .. } if name == "angle_deg" => {
                if value <= 0.0 || value >= 360.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.angle_deg: angle between instances must be in (0, 360) degrees, \
                         got {value}"
                    )));
                }
                *angle = value.to_radians();
                Ok(())
            }
            FeatureKind::Shell { thickness, .. } if name == "thickness" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.thickness: shell wall thickness must be > 0 mm, got {value}"
                    )));
                }
                *thickness = value;
                Ok(())
            }
            FeatureKind::LinearPattern { spacing, .. } if name == "spacing" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.spacing: pattern spacing must be > 0 mm, got {value}"
                    )));
                }
                *spacing = value;
                Ok(())
            }
            FeatureKind::Hole {
                center,
                diameter,
                depth,
                counterbore,
                ..
            } => {
                let pos = |what: &str| {
                    (value > 0.0).then_some(()).ok_or_else(|| {
                        DocError::Validation(format!(
                            "{id}.{name}: {what} must be > 0 mm, got {value}"
                        ))
                    })
                };
                match (name, counterbore.as_mut(), depth.as_mut()) {
                    ("diameter", cb, _) => {
                        pos("hole diameter")?;
                        if let Some(c) = cb
                            && c.diameter <= value
                        {
                            return Err(DocError::Validation(format!(
                                "{id}.diameter: the hole ({value} mm) must be smaller than its \
                                 counterbore ({} mm)",
                                c.diameter
                            )));
                        }
                        *diameter = value;
                    }
                    ("depth", cb, Some(d)) => {
                        pos("hole depth")?;
                        if let Some(c) = cb
                            && c.depth >= value
                        {
                            return Err(DocError::Validation(format!(
                                "{id}.depth: the hole ({value} mm) must be deeper than its \
                                 counterbore ({} mm)",
                                c.depth
                            )));
                        }
                        *d = value;
                    }
                    ("cbore_diameter", Some(c), _) => {
                        if value <= *diameter {
                            return Err(DocError::Validation(format!(
                                "{id}.cbore_diameter: the counterbore ({value} mm) must be wider \
                                 than the hole ({diameter} mm)"
                            )));
                        }
                        c.diameter = value;
                    }
                    ("cbore_depth", Some(c), d) => {
                        pos("counterbore depth")?;
                        if let Some(d) = d
                            && value >= *d
                        {
                            return Err(DocError::Validation(format!(
                                "{id}.cbore_depth: the counterbore ({value} mm) must be shallower \
                                 than the hole ({d} mm)"
                            )));
                        }
                        c.depth = value;
                    }
                    ("center_x", _, _) => center[0] = value,
                    ("center_y", _, _) => center[1] = value,
                    _ => {
                        return Err(DocError::UnknownParameter {
                            feature: id,
                            name: name.into(),
                        });
                    }
                }
                Ok(())
            }
            FeatureKind::DirectEdit {
                op: DirectOp::OffsetFace { distance },
                ..
            } if name == "distance" => {
                if value == 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.distance: a face offset must be non-zero"
                    )));
                }
                *distance = value;
                Ok(())
            }
            FeatureKind::DirectEdit {
                op: DirectOp::ResizeCylinder { diameter },
                ..
            } if name == "diameter" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.diameter: diameter must be > 0 mm, got {value}"
                    )));
                }
                *diameter = value;
                Ok(())
            }
            FeatureKind::Fillet { radius, .. } if name == "radius" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.radius: fillet radius must be > 0 mm, got {value}"
                    )));
                }
                *radius = value;
                Ok(())
            }
            FeatureKind::Chamfer { distance, .. } if name == "distance" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.distance: chamfer distance must be > 0 mm, got {value}"
                    )));
                }
                *distance = value;
                Ok(())
            }
            FeatureKind::Pocket { depth, .. } if name == "depth" => {
                if value <= 0.0 {
                    return Err(DocError::Validation(format!(
                        "{id}.depth: pocket depth must be > 0 mm, got {value}"
                    )));
                }
                *depth = value;
                Ok(())
            }
            _ => Err(DocError::UnknownParameter {
                feature: id,
                name: name.into(),
            }),
        }
    }
}

/// Largest linear pattern count (bounds the boolean work of one feature).
pub const MAX_PATTERN_COUNT: u32 = 100;

/// Position of a template sketch's single fixed anchor point (the template centre),
/// exposed as the editable parameters `center_x` / `center_y` (mm, sketch-plane frame).
/// Editor sketches (with an `origin` point) have no movable anchor.
pub fn anchor(sketch: &rcad_sketch::Sketch) -> Option<(f64, f64)> {
    if sketch.origin.is_some() {
        return None;
    }
    let mut fixed = sketch.constraints.iter().filter_map(|c| match c {
        rcad_sketch::Constraint::FixedPoint { x, y, .. } => Some((*x, *y)),
        _ => None,
    });
    let first = fixed.next()?;
    fixed.next().is_none().then_some(first)
}

/// The authoritative model: ordered feature history plus the id allocator.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
pub struct Document {
    pub features: Vec<Feature>,
    pub next_id: u32,
    /// Body metadata (v3), in creation order. See ADR 0003.
    #[serde(default)]
    pub bodies: Vec<BodyInfo>,
    #[serde(default = "one")]
    pub next_body_id: u32,
    /// Embedded imported source files (v3).
    #[serde(default)]
    pub blobs: Vec<Blob>,
    #[serde(default = "one")]
    pub next_blob_id: u32,
    /// Named user parameters (v4), in display order.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub parameters: Vec<crate::Parameter>,
}

fn one() -> u32 {
    1
}

impl Document {
    pub fn new() -> Self {
        Self {
            features: Vec::new(),
            next_id: 1,
            bodies: Vec::new(),
            next_body_id: 1,
            blobs: Vec::new(),
            next_blob_id: 1,
            parameters: Vec::new(),
        }
    }

    /// Allocate a body id and register its metadata (`name` must be unique;
    /// see [`Document::default_body_name`]).
    pub fn add_body(&mut self, name: impl Into<String>) -> BodyId {
        let id = BodyId(self.next_body_id.clamp(1, u32::MAX - 1));
        self.next_body_id = id.0.saturating_add(1);
        self.bodies.push(BodyInfo {
            id,
            name: name.into(),
            visible: true,
        });
        id
    }

    pub fn body(&self, id: BodyId) -> Result<&BodyInfo> {
        self.bodies
            .iter()
            .find(|b| b.id == id)
            .ok_or_else(|| DocError::Validation(format!("unknown body {id}")))
    }

    pub fn body_mut(&mut self, id: BodyId) -> Result<&mut BodyInfo> {
        self.bodies
            .iter_mut()
            .find(|b| b.id == id)
            .ok_or_else(|| DocError::Validation(format!("unknown body {id}")))
    }

    /// Unique default body name like "Body1".
    pub fn default_body_name(&self) -> String {
        (1..)
            .map(|i| format!("Body{i}"))
            .find(|n| !self.bodies.iter().any(|b| &b.name == n))
            .unwrap_or_else(|| "Body".to_string())
    }

    /// Embed a source file; returns its id.
    pub fn add_blob(&mut self, file_name: &str, bytes: &[u8]) -> BlobId {
        let id = BlobId(self.next_blob_id.clamp(1, u32::MAX - 1));
        self.next_blob_id = id.0.saturating_add(1);
        self.blobs.push(Blob::new(id, file_name, bytes));
        id
    }

    pub fn blob(&self, id: BlobId) -> Result<&Blob> {
        self.blobs
            .iter()
            .find(|b| b.id == id)
            .ok_or_else(|| DocError::Validation(format!("unknown embedded file {id}")))
    }

    /// Feature that creates body `id`.
    pub fn body_creator(&self, id: BodyId) -> Option<FeatureId> {
        self.features
            .iter()
            .find(|f| f.created_bodies().contains(&id))
            .map(|f| f.id)
    }

    /// All features `f` depends on: explicit references plus the creator of
    /// its target body.
    pub fn dependencies_of(&self, f: &Feature) -> Vec<FeatureId> {
        let mut d = f.dependencies();
        if let Some(t) = f.target_body()
            && let Some(c) = self.body_creator(t)
            && !d.contains(&c)
        {
            d.push(c);
        }
        d
    }

    /// Body that `f` modifies without creating it: a Join/Cut/Pocket target,
    /// the seed's target for patterns and mirrors, the faces' body for a
    /// chamfer.
    pub fn modified_body(&self, f: &Feature) -> Option<BodyId> {
        if let Some(t) = f.target_body() {
            return Some(t);
        }
        match &f.kind {
            FeatureKind::LinearPattern { seed, .. }
            | FeatureKind::CircularPattern { seed, .. }
            | FeatureKind::Mirror { seed, .. } => {
                self.feature(*seed).ok().and_then(Feature::target_body)
            }
            FeatureKind::Chamfer { a, .. } | FeatureKind::Fillet { a, .. } => self.face_body(a),
            FeatureKind::Shell { extrude, .. } => self
                .feature(*extrude)
                .ok()
                .and_then(|e| e.created_bodies().first().copied()),
            _ => None,
        }
    }

    /// Body owning the face `r` names (from the definitions only).
    pub fn face_body(&self, r: &FaceRef) -> Option<BodyId> {
        self.face_body_depth(r, 0)
    }

    fn face_body_depth(&self, r: &FaceRef, depth: usize) -> Option<BodyId> {
        if depth > self.features.len() {
            return None; // a (malformed) reference loop
        }
        match r.role {
            FaceRole::Imported { body, .. } => Some(body),
            _ => {
                let f = self.feature(r.feature).ok()?;
                match &f.kind {
                    FeatureKind::LinearPattern { seed, .. }
                    | FeatureKind::CircularPattern { seed, .. }
                    | FeatureKind::Mirror { seed, .. } => {
                        return self.feature(*seed).ok()?.target_body();
                    }
                    FeatureKind::Chamfer { a, .. } | FeatureKind::Fillet { a, .. } => {
                        return self.face_body_depth(a, depth + 1);
                    }
                    _ => {}
                }
                match f.created_bodies().first() {
                    Some(b) => Some(*b),
                    None => f.target_body(),
                }
            }
        }
    }

    /// [`Document::dependencies_of`] plus the ordering constraint between
    /// features acting on the same body: a feature that modifies a body comes
    /// after the previous feature (in history) that created or modified it.
    /// Without this, re-attaching a sketch to a face of a later feature could
    /// silently swap two modifiers of one body; with it, that is a cycle and
    /// the edit is refused. Not used for deletion (deleting a modifier that
    /// nothing references is allowed).
    pub fn ordering_dependencies_of(&self, f: &Feature) -> Vec<FeatureId> {
        let mut d = self.dependencies_of(f);
        if let Some(b) = self.modified_body(f)
            && let Some(p) = self.features.iter().position(|x| x.id == f.id)
            && let Some(prev) = self.features[..p]
                .iter()
                .rev()
                .find(|x| x.created_bodies().contains(&b) || self.modified_body(x) == Some(b))
            && !d.contains(&prev.id)
        {
            d.push(prev.id);
        }
        d
    }

    /// Every evaluated feature's dependencies are evaluated: a feature that is
    /// not suppressed may not depend on a suppressed one.
    pub fn check_suppression(&self) -> Result<()> {
        for f in self.features.iter().filter(|f| !f.suppressed) {
            for d in self.dependencies_of(f) {
                if let Ok(g) = self.feature(d)
                    && g.suppressed
                {
                    return Err(DocError::BrokenReference {
                        from: f.id,
                        detail: format!(
                            "{} ({}) depends on {} ({}), which is suppressed; suppress {} too \
                             (with dependents) or restore {}",
                            f.id, f.name, g.id, g.name, f.id, g.id
                        ),
                    });
                }
            }
        }
        Ok(())
    }

    /// `id` and every feature that depends on it, directly or transitively
    /// (history order).
    pub fn with_dependents(&self, id: FeatureId) -> Vec<FeatureId> {
        let mut out = vec![id];
        let mut i = 0;
        while i < out.len() {
            for d in self.dependents_of(out[i]) {
                if !out.contains(&d) {
                    out.push(d);
                }
            }
            i += 1;
        }
        self.features
            .iter()
            .map(|f| f.id)
            .filter(|f| out.contains(f))
            .collect()
    }

    /// Features that depend on `id` (explicitly or through a body target).
    pub fn dependents_of(&self, id: FeatureId) -> Vec<FeatureId> {
        self.features
            .iter()
            .filter(|f| self.dependencies_of(f).contains(&id))
            .map(|f| f.id)
            .collect()
    }

    /// Consistency of bodies and blobs (ADR 0003): every body is created by
    /// exactly one feature and has exactly one metadata entry; targets name
    /// existing bodies; blob references resolve; unused blobs are removed by
    /// [`Document::prune_blobs`], so they are an error here.
    pub fn validate_bodies(&self) -> Result<()> {
        let mut created = std::collections::HashMap::new();
        for f in &self.features {
            for b in f.created_bodies() {
                if b.0 == 0 || b.0 >= self.next_body_id {
                    return Err(DocError::Validation(format!(
                        "{}: body id {b} is unassigned or >= next_body_id {}",
                        f.id, self.next_body_id
                    )));
                }
                if let Some(prev) = created.insert(b, f.id) {
                    return Err(DocError::Validation(format!(
                        "body {b} is created by both {prev} and {}",
                        f.id
                    )));
                }
            }
        }
        let mut seen = std::collections::HashSet::new();
        for info in &self.bodies {
            if !seen.insert(info.id) {
                return Err(DocError::Validation(format!(
                    "duplicate body entry {}",
                    info.id
                )));
            }
            if !created.contains_key(&info.id) {
                return Err(DocError::Validation(format!(
                    "body {} ({}) is not created by any feature",
                    info.id, info.name
                )));
            }
        }
        for (b, f) in &created {
            if !seen.contains(b) {
                return Err(DocError::Validation(format!(
                    "{f}: body {b} has no body entry"
                )));
            }
        }
        for f in &self.features {
            if let Some(t) = f.target_body()
                && !created.contains_key(&t)
            {
                return Err(DocError::BrokenReference {
                    from: f.id,
                    detail: format!("target body {t} does not exist"),
                });
            }
            if let Some(b) = f.blob() {
                self.blob(b).map_err(|_| DocError::BrokenReference {
                    from: f.id,
                    detail: format!("embedded file {b} is missing"),
                })?;
            }
        }
        let mut blob_ids = std::collections::HashSet::new();
        for b in &self.blobs {
            if !blob_ids.insert(b.id) || b.id.0 == 0 || b.id.0 >= self.next_blob_id {
                return Err(DocError::Validation(format!("invalid blob id {}", b.id)));
            }
        }
        Ok(())
    }

    /// Drop embedded files no feature references (after deleting an import).
    pub fn prune_blobs(&mut self) {
        let used: std::collections::HashSet<BlobId> =
            self.features.iter().filter_map(Feature::blob).collect();
        self.blobs.retain(|b| used.contains(&b.id));
    }

    /// Drop body entries no feature creates (after deleting a body's creator).
    pub fn prune_bodies(&mut self) {
        let made: std::collections::HashSet<BodyId> = self
            .features
            .iter()
            .flat_map(Feature::created_bodies)
            .collect();
        self.bodies.retain(|b| made.contains(&b.id));
    }

    pub fn feature(&self, id: FeatureId) -> Result<&Feature> {
        self.features
            .iter()
            .find(|f| f.id == id)
            .ok_or(DocError::UnknownFeature(id))
    }

    pub fn feature_mut(&mut self, id: FeatureId) -> Result<&mut Feature> {
        self.features
            .iter_mut()
            .find(|f| f.id == id)
            .ok_or(DocError::UnknownFeature(id))
    }

    /// Append a feature, allocating its id. Ids saturate at `u32::MAX - 1`; at that
    /// point `evaluation_order` rejects the document instead of wrapping.
    pub fn push(&mut self, name: impl Into<String>, kind: FeatureKind) -> FeatureId {
        let id = FeatureId(self.next_id.clamp(1, u32::MAX - 1));
        self.next_id = id.0.saturating_add(1);
        self.features.push(Feature {
            id,
            name: name.into(),
            kind,
            notes: vec![],
            expressions: Default::default(),
            suppressed: false,
        });
        id
    }

    /// Append a new-body distance extrusion of `sketch`, allocating its body
    /// (default name). Convenience for the common case.
    pub fn push_extrude(
        &mut self,
        name: impl Into<String>,
        sketch: FeatureId,
        distance: f64,
    ) -> FeatureId {
        let body = self.add_body(self.default_body_name());
        self.push(
            name,
            FeatureKind::extrude(sketch, distance, Operation::NewBody { body }),
        )
    }

    /// Unique default name like "Sketch1".
    pub fn default_name(&self, prefix: &str) -> String {
        (1..)
            .map(|i| format!("{prefix}{i}"))
            .find(|n| !self.features.iter().any(|f| &f.name == n))
            .unwrap_or_else(|| prefix.to_string())
    }

    /// Feature ids in a valid evaluation order (Kahn's algorithm, ties broken by
    /// history position for determinism). Errors on unknown ids or cycles.
    pub fn evaluation_order(&self) -> Result<Vec<FeatureId>> {
        let n = self.features.len();
        let pos = |id: FeatureId| self.features.iter().position(|f| f.id == id);
        let mut seen = std::collections::HashSet::new();
        for f in &self.features {
            if !seen.insert(f.id) {
                return Err(DocError::Validation(format!(
                    "duplicate feature id {}",
                    f.id
                )));
            }
            if f.id.0 >= self.next_id {
                return Err(DocError::Validation(format!(
                    "feature id {} >= next_id {}",
                    f.id, self.next_id
                )));
            }
        }
        let mut indeg = vec![0usize; n];
        let mut users: Vec<Vec<usize>> = vec![Vec::new(); n];
        for (i, f) in self.features.iter().enumerate() {
            for d in self.ordering_dependencies_of(f) {
                let j = pos(d).ok_or(DocError::BrokenReference {
                    from: f.id,
                    detail: format!("depends on missing feature {d}"),
                })?;
                indeg[i] += 1;
                users[j].push(i);
            }
        }
        let mut ready: std::collections::BTreeSet<usize> =
            (0..n).filter(|&i| indeg[i] == 0).collect();
        let mut order = Vec::with_capacity(n);
        while let Some(i) = ready.pop_first() {
            order.push(self.features[i].id);
            for &u in &users[i] {
                indeg[u] -= 1;
                if indeg[u] == 0 {
                    ready.insert(u);
                }
            }
        }
        if order.len() != n {
            let stuck = (0..n)
                .filter(|&i| indeg[i] > 0)
                .map(|i| self.features[i].id)
                .collect();
            return Err(DocError::Cycle(stuck));
        }
        Ok(order)
    }
}
