/// Stable feature identifier. Allocated monotonically, never reused.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct FeatureId(pub u32);

impl fmt::Display for FeatureId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "F{}", self.0)
    }
}

/// Stable body identifier (ADR 0003). Allocated monotonically from
/// [`Document::next_body_id`], stored in the creating feature, never reused.
/// `BodyId(0)` means "unassigned" and only exists transiently while migrating
/// v1/v2 files.
#[derive(
    Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, Default,
)]
pub struct BodyId(pub u32);

impl fmt::Display for BodyId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "B{}", self.0)
    }
}

/// User-facing body metadata. Geometry comes from the creating feature.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BodyInfo {
    pub id: BodyId,
    pub name: String,
    #[serde(default = "yes")]
    pub visible: bool,
    /// Physical material for mass properties (format v6); None: not
    /// assigned. Separate from appearance.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub material: Option<crate::Material>,
}

fn yes() -> bool {
    true
}

/// Identifier of an embedded binary/text blob (imported source files).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct BlobId(pub u32);

impl fmt::Display for BlobId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "blob{}", self.0)
    }
}

/// An embedded source file (immutable once added). The native document keeps
/// the bytes so it never depends on the original path (ADR 0003).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Blob {
    pub id: BlobId,
    /// Original file name (provenance only; never reopened).
    pub file_name: String,
    /// Size of the decoded bytes.
    pub len: u64,
    /// FNV-1a 64 of the decoded bytes, hex (integrity check, not security).
    pub fnv64: String,
    /// The bytes: UTF-8 text verbatim, or base64.
    pub encoding: BlobEncoding,
    pub data: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum BlobEncoding {
    Text,
    Base64,
}

impl Blob {
    /// Embed `bytes` (stored as text when they are valid UTF-8, else base64).
    pub fn new(id: BlobId, file_name: &str, bytes: &[u8]) -> Self {
        let (encoding, data) = match std::str::from_utf8(bytes) {
            Ok(t) => (BlobEncoding::Text, t.to_string()),
            Err(_) => (BlobEncoding::Base64, crate::blob::base64_encode(bytes)),
        };
        Self {
            id,
            file_name: file_name.to_string(),
            len: bytes.len() as u64,
            fnv64: crate::blob::fnv64_hex(bytes),
            encoding,
            data,
        }
    }

    /// Decoded bytes, verified against the stored length and hash.
    pub fn bytes(&self) -> Result<Vec<u8>> {
        let b = match self.encoding {
            BlobEncoding::Text => self.data.as_bytes().to_vec(),
            BlobEncoding::Base64 => crate::blob::base64_decode(&self.data)
                .ok_or_else(|| DocError::File(format!("{}: invalid base64 data", self.id)))?,
        };
        if b.len() as u64 != self.len || crate::blob::fnv64_hex(&b) != self.fnv64 {
            return Err(DocError::File(format!(
                "{} ({}): embedded data is corrupt (length/hash mismatch)",
                self.id, self.file_name
            )));
        }
        Ok(b)
    }
}

/// Semantic role of a face generated by a feature. Resolved from the generating
/// feature's definition, then validated against the B-rep; never a face index.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum FaceRole {
    /// Planar cap at the end of an extrusion (the "top" for +Z extrusions). For a
    /// blind cut: the floor, outward normal pointing back toward the opening.
    ExtrudeEndCap,
    /// Planar cap at the start of an extrusion (on the profile plane).
    ExtrudeStartCap,
    /// Planar side face generated by profile line `entity` (sketch entity id) of an
    /// extrusion (New/Join: outer wall; Cut: wall of the removed region).
    ExtrudeSide { entity: u32 },
    /// Face `face` (stable import index: position in the solid's face order
    /// right after import) of imported body `body`. Sketches and other plane
    /// users accept planar faces only; direct edits
    /// ([`FeatureKind::DirectEdit`]) also name cylindrical faces this way.
    Imported { body: BodyId, face: u32 },
    /// Face of an occurrence made by a pattern or mirror feature: the
    /// face that seed tool `tool` (0 for an extrusion; a Hole: 0 = counterbore
    /// when present, then the hole) generates at occurrence `instance` (pattern:
    /// 1..count-1, the seed is occurrence 0 and keeps its own references;
    /// mirror: 1). The identity survives count changes; an occurrence that no
    /// longer exists is a `BrokenReference`, never another occurrence.
    Copy {
        instance: u32,
        #[serde(default)]
        tool: u32,
        of: CopiedRole,
    },
    /// The planar face made by a Chamfer feature.
    Chamfer,
}

/// Role of a seed tool's face within a pattern/mirror occurrence
/// ([`FaceRole::Copy`]); same meaning as the extrusion roles.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum CopiedRole {
    EndCap,
    StartCap,
    Side { entity: u32 },
}

impl CopiedRole {
    /// The equivalent extrusion role (on the occurrence's own tool).
    pub fn extrude_role(self) -> FaceRole {
        match self {
            CopiedRole::EndCap => FaceRole::ExtrudeEndCap,
            CopiedRole::StartCap => FaceRole::ExtrudeStartCap,
            CopiedRole::Side { entity } => FaceRole::ExtrudeSide { entity },
        }
    }
}

/// Persistent face selection: originating feature + generated-face role.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct FaceRef {
    pub feature: FeatureId,
    pub role: FaceRole,
}

#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub enum SketchPlane {
    /// World XY plane through the origin, normal +Z.
    WorldXY,
    /// World XZ plane through the origin: local x = world X, local y = world Z, normal -Y.
    WorldXZ,
    /// World YZ plane through the origin: local x = world Y, local y = world Z, normal +X.
    WorldYZ,
    /// A planar face generated by an earlier feature.
    Face(FaceRef),
    /// Construction plane: `base` moved `distance` mm along its normal
    /// (a face's outward normal; +Z / −Y / +X for the world planes), same
    /// in-plane axes. Parameter "plane_offset" of the sketch (bindable). A
    /// face base resolves like `Face` (BrokenReference when it is gone).
    /// `angle` (radians, default 0, written only when non-zero) first
    /// tilts the base plane about its local X axis through its origin
    /// (right-handed: +angle turns local +Y toward the normal), then the offset
    /// is applied along the tilted normal. Parameter "plane_angle_deg".
    Offset {
        base: PlaneBase,
        distance: f64,
        #[serde(default, skip_serializing_if = "is_zero")]
        angle: f64,
    },
}

fn is_zero(v: &f64) -> bool {
    *v == 0.0
}

// `distance` is validated finite wherever a plane is accepted, so equality is
// reflexive in practice.
impl Eq for SketchPlane {}

/// Base of an offset construction plane.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum PlaneBase {
    WorldXY,
    WorldXZ,
    WorldYZ,
    Face(FaceRef),
}

impl PlaneBase {
    /// The base as a plain sketch plane.
    pub fn plane(self) -> SketchPlane {
        match self {
            PlaneBase::WorldXY => SketchPlane::WorldXY,
            PlaneBase::WorldXZ => SketchPlane::WorldXZ,
            PlaneBase::WorldYZ => SketchPlane::WorldYZ,
            PlaneBase::Face(r) => SketchPlane::Face(r),
        }
    }
}

impl SketchPlane {
    /// The face this plane is on or offset from, if any.
    pub fn face(&self) -> Option<FaceRef> {
        match *self {
            SketchPlane::Face(r)
            | SketchPlane::Offset {
                base: PlaneBase::Face(r),
                ..
            } => Some(r),
            _ => None,
        }
    }

    /// `(base plane, offset)`: an offset plane's base and distance, else
    /// `(self, 0)`.
    pub fn base_and_offset(&self) -> (SketchPlane, f64) {
        match *self {
            SketchPlane::Offset { base, distance, .. } => (base.plane(), distance),
            p => (p, 0.0),
        }
    }

    /// Tilt (radians) of a construction plane about its base's local X axis.
    pub fn angle(&self) -> f64 {
        match *self {
            SketchPlane::Offset { angle, .. } => angle,
            _ => 0.0,
        }
    }
}

/// What an extrusion does with its tool body (ADR 0003).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Operation {
    /// Create body `body`.
    NewBody { body: BodyId },
    /// Union the tool into `target`.
    Join { target: BodyId },
    /// Subtract the tool from `target`.
    Cut { target: BodyId },
    /// Keep only the part of `target` inside the tool (format v6).
    Intersect { target: BodyId },
}

impl Default for Operation {
    /// v1/v2 extrusions created the (single) base body; the id is assigned by migration.
    fn default() -> Self {
        Operation::NewBody { body: BodyId(0) }
    }
}

/// How far an extrusion goes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Extent {
    /// `distance` mm along the direction.
    #[default]
    Distance,
    /// Cut only: through all material of the target on both sides of the sketch
    /// plane along its normal (cutter length derived from the target's extent).
    ThroughAll,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum CutExtent {
    /// Through all material, both directions along the sketch normal.
    ThroughAll,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum FeatureKind {
    Sketch {
        plane: SketchPlane,
        sketch: Sketch,
        /// Projected geometry kept associative (format v6): each link
        /// drives sketch entities pinned by `FixedPoint` constraints, updated
        /// from the source at every regeneration.
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        links: Vec<ProjectionLink>,
    },
    /// New-body revolve of a sketch profile about the sketch's local Y axis.
    /// `angle` is in radians (exposed as parameter `angle_deg`).
    Revolve {
        sketch: FeatureId,
        angle: f64,
        /// Body created (v3; assigned by migration for older files).
        #[serde(default)]
        body: BodyId,
        /// Format v6 when not the default: the axis, and `reverse`
        /// (sweep toward +normal instead of the default −normal).
        #[serde(default, skip_serializing_if = "RevolveAxis::is_default")]
        axis: RevolveAxis,
        #[serde(default, skip_serializing_if = "std::ops::Not::not")]
        reverse: bool,
        /// Join to / cut from an existing body instead of a new body
        /// (`body` is then unused). Built with the kernel boolean and checked
        /// independently by point membership (`rcad_kernel::combine`).
        #[serde(default, skip_serializing_if = "Option::is_none")]
        merge: Option<Operation>,
    },
    /// Extrusion of a sketch profile along the sketch normal (or against it when
    /// `reverse`): a new body, or joined to / cut from an explicit target body.
    Extrude {
        sketch: FeatureId,
        distance: f64,
        #[serde(default)]
        operation: Operation,
        #[serde(default)]
        extent: Extent,
        #[serde(default)]
        reverse: bool,
        /// Extrude only this bounded region of the sketch (additive:
        /// absent = the whole profile, exactly as before). Resolved by identity
        /// at every regeneration; a region that no longer exists is a
        /// `BrokenReference`, never another region.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        region: Option<rcad_sketch::RegionRef>,
        /// Extent options (format v6; absent = a plain extrusion).
        #[serde(default, skip_serializing_if = "ExtrudeOptions::is_plain")]
        options: ExtrudeOptions,
    },
    /// Legacy (v1/v2) circular through-all cut; see [`FeatureKind::Extrude`] with
    /// [`Operation::Cut`] for general cuts.
    Cut {
        sketch: FeatureId,
        extent: CutExtent,
        #[serde(default)]
        target: BodyId,
    },
    /// Blind cut: removes the sketch profile from the sketched extrusion cap
    /// inward (against the cap's outward normal) to `depth` mm. Product limits:
    /// circular profile sketched on an end/start cap of the base extrusion,
    /// strictly inside it, 0 < depth < extrusion thickness (a through hole is
    /// `Cut`). Added in format v2; absent from v1 files.
    Pocket {
        sketch: FeatureId,
        depth: f64,
        #[serde(default)]
        target: BodyId,
    },
    /// Base feature: exact solids imported from an embedded STEP file. One body
    /// per imported solid (in file order). No source feature history.
    ImportStep {
        blob: BlobId,
        /// Unit scale used when the file declares no length unit (mm per unit).
        #[serde(default)]
        unit_override_to_mm: Option<f64>,
        bodies: Vec<BodyId>,
    },
    /// Base feature: a triangle mesh (STL) body, scaled by `to_mm` (STL is unitless).
    ImportMesh {
        blob: BlobId,
        to_mm: f64,
        body: BodyId,
    },
    /// Base feature: mesh bodies from an embedded 3MF package, one per build item
    /// in file order (units declared by the file).
    Import3mf { blob: BlobId, bodies: Vec<BodyId> },
    /// Repeat the tool of `seed` (an Extrude Join/Cut or a Hole) `count - 1` more
    /// times (count 1 = the seed only, no copies), each
    /// shifted by `spacing` mm along `direction` (seed sketch-plane coordinates,
    /// normalized), on the seed's target body. The seed is instance 0.
    LinearPattern {
        seed: FeatureId,
        count: u32,
        spacing: f64,
        direction: [f64; 2],
    },
    /// Apply the reflection of `seed`'s tool (an Extrude Join or Cut) across
    /// `plane` (a world plane through the origin or a planar face) to the seed's
    /// target body. The seed itself stays; this adds the mirrored copy.
    Mirror { seed: FeatureId, plane: SketchPlane },
    /// Repeat the tool of `seed` (an Extrude Join/Cut) `count - 1` more times,
    /// each rotated by a further `angle` (radians; parameter `angle_deg`, counter-
    /// clockwise about the seed sketch's normal) about `center` (seed sketch-plane
    /// coordinates), on the seed's target body. The seed is instance 0.
    CircularPattern {
        seed: FeatureId,
        count: u32,
        angle: f64,
        center: [f64; 2],
    },
    /// Equal-distance chamfer of the straight convex edge where planar faces `a`
    /// and `b` (semantic references on one body) meet, `distance` mm along each.
    Chamfer {
        a: FaceRef,
        b: FaceRef,
        distance: f64,
    },
    /// Exact solid fillet of the straight convex edge where planar
    /// faces `a` and `b` meet: an exact cylinder of `radius` mm tangent to
    /// both. Scope (`rcad_kernel::fillet_edge`): the body is prismatic along
    /// the edge (planar faces parallel/perpendicular to it), end faces
    /// perpendicular; refused otherwise with the reason. Parameter "radius".
    Fillet { a: FaceRef, b: FaceRef, radius: f64 },
    /// Exact loft (ADR 0008) between the closed profiles of sketches
    /// `a` and `b` on parallel planes, as new body `body`: equal-count
    /// polygons whose corresponding edges are parallel (planar sides; vertex
    /// correspondence by the rule in ADR 0008), or two coaxial circles (cone
    /// frustum). Anything else is refused with the reason.
    Loft {
        a: FeatureId,
        b: FeatureId,
        body: BodyId,
        /// Format v6: intermediate section sketches, in order from
        /// `a` to `b` (straight-edged profiles; `rcad_kernel::loft_sections`).
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        via: Vec<FeatureId>,
    },
    /// Exact sweep (ADR 0009) of the closed profile of sketch `profile`
    /// along the open chain of lines and arcs of sketch `path`, as new body
    /// `body`. The path starts at the profile sketch's origin, leaving along
    /// its normal; joints tangent; planar path. Refused otherwise by name.
    Sweep {
        profile: FeatureId,
        path: FeatureId,
        body: BodyId,
    },
    /// Round hole drilled into `target` from `plane` (which must hold a
    /// planar face of the target; the hole goes into the material), centred at
    /// `center` (plane coordinates): `diameter`, `depth` mm from the face
    /// (`None`: through all), and an optional counterbore. Parameters
    /// "diameter", "depth", "cbore_diameter", "cbore_depth", "center_x",
    /// "center_y". Built as a counterbore cut then the hole cut, each checked
    /// like an Extrude Cut (ADR 0005). Countersinks are not supported.
    Hole {
        plane: SketchPlane,
        center: [f64; 2],
        diameter: f64,
        #[serde(default)]
        depth: Option<f64>,
        #[serde(default)]
        counterbore: Option<Counterbore>,
        target: BodyId,
    },
    /// Scoped shell (docs/SHELL.md): hollows the body of `extrude` (a New
    /// Body extrusion of a single closed loop of lines/arcs or a circle, no
    /// holes, no picked region) leaving walls and a floor `thickness` mm thick,
    /// open at the `open` cap (`ExtrudeEndCap` or `ExtrudeStartCap`). Built as a
    /// blind cut of the profile offset inward by `thickness`, from the open cap
    /// to `distance − thickness` deep, checked like an Extrude Cut (ADR 0005).
    /// Not a general shell: other faces and later features are not offset.
    /// Parameter "thickness".
    Shell {
        extrude: FeatureId,
        open: FaceRole,
        thickness: f64,
    },
    /// Rigid move of body `body` (format v6): rotate `angle` rad
    /// (parameter `angle_deg`) about the axis through `origin` along `axis`,
    /// then translate by `translate` (parameters `tx`, `ty`, `tz`). With
    /// `copy`, the moved result is the new, independent body `copy` and
    /// `body` stays. Faces made before the move keep resolving (references
    /// are transformed); pattern/mirror/shell seeds made before a move of
    /// their body are refused.
    MoveBody {
        body: BodyId,
        translate: [f64; 3],
        #[serde(default)]
        origin: [f64; 3],
        #[serde(default = "z_axis")]
        axis: [f64; 3],
        #[serde(default)]
        angle: f64,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        copy: Option<BodyId>,
    },
    /// Split body `body` by `plane` (format v6): `body` keeps the part
    /// behind the plane (against its normal), new body `new_body` gets the
    /// part in front of it. Each part is an exact, result-checked cut by a
    /// half-space box (ADR 0005/0006); a plane that misses the body, or a
    /// side that falls apart into several solids, is refused. Faces of the
    /// new body are not referencable by role. Parameters "plane_offset",
    /// "plane_angle_deg" for an offset plane.
    SplitBody {
        body: BodyId,
        plane: SketchPlane,
        new_body: BodyId,
    },
    /// Shell from any planar face (format v6): hollow the body under
    /// `face` (left open) to walls and floor `thickness` thick, for bodies
    /// prismatic along the face normal (all walls perpendicular to the face):
    /// the face's outer boundary offset inward by the thickness is cut down
    /// to one thickness above the opposite cap (exact slab construction,
    /// result-checked). Refused otherwise by name. Parameter "thickness".
    ShellFace { face: FaceRef, thickness: f64 },
    /// Align (format v6): move the body owning planar face `from` so
    /// that face lies on the plane of face `to` (of another body), facing it
    /// (outward normals opposite), `offset` mm apart along `to`'s normal; the
    /// smallest rotation is used and `from`'s origin is projected straight
    /// onto the plane. Associative: regenerated from both faces; logged like a
    /// move. Parameter "offset".
    AlignBody {
        from: FaceRef,
        to: FaceRef,
        #[serde(default)]
        offset: f64,
    },
    /// Uniform scale of body `body` by `factor` about `center` (format
    /// v6), in place; faces made before it keep resolving (scaled with the
    /// body, like moves). Parameter "factor" (ratio).
    ScaleBody {
        body: BodyId,
        #[serde(default)]
        center: [f64; 3],
        factor: f64,
    },
    /// Sheet-metal contour flange (`crate::sheet`,
    /// format v6): the open line chain of sketch `sketch` is one surface of a
    /// sheet `thickness` thick (material right of the chain, left with
    /// `flip`), with cylindrical bends of inner `radius` at its corners,
    /// extruded `width` along the sketch normal as new body `body`. Flat
    /// pattern by K-factor (`k_factor`). Parameters "thickness", "radius",
    /// "k_factor", "width".
    SheetMetal {
        sketch: FeatureId,
        thickness: f64,
        radius: f64,
        k_factor: f64,
        width: f64,
        #[serde(default, skip_serializing_if = "std::ops::Not::not")]
        flip: bool,
        body: BodyId,
    },
    /// Direct edit (ADR 0010) of an imported STEP body: `face` is an
    /// imported face (`FaceRole::Imported`, by stable import index) and `op`
    /// what is done to it, exactly (`rcad_kernel::{offset_face,
    /// resize_cylinder, remove_cylinder}`). This is direct-edit history, not
    /// recovered feature history (STEP has none). Applies only while the body
    /// has been changed by nothing but its import and direct edits; a face
    /// removed by an earlier edit is a `BrokenReference`.
    DirectEdit { face: FaceRef, op: DirectOp },
    /// Exact countersink at the entry of the hole made
    /// by Hole feature `hole`: a cone of `diameter` mm at the entry face and
    /// included `angle` (radians; parameter `angle_deg`, default 90°), built
    /// directly into the topology (`rcad_kernel::countersink`; Truck cannot
    /// boolean a cone). Entry face planar and perpendicular to the hole, no
    /// counterbore; refused with the reason when the countersink leaves the
    /// face or reaches the end of the hole. Patterns/mirrors of the hole do not
    /// copy it. Parameters "diameter", "angle_deg".
    Countersink {
        hole: FeatureId,
        diameter: f64,
        angle: f64,
    },
    /// Body Combine (format v6): `target` joined with / cut by /
    /// intersected with the `tools` bodies, in order (`rcad_kernel::combine`:
    /// Truck booleans plus an independent membership/volume check against the
    /// inputs). Without `keep_tools` the tool bodies are consumed: they leave
    /// the evaluated model (their creators stay in history; later features
    /// using them are broken references). Faces of consumed tools are not
    /// referencable afterwards.
    Combine {
        target: BodyId,
        tools: Vec<BodyId>,
        op: rcad_kernel::CombineOp,
        #[serde(default, skip_serializing_if = "std::ops::Not::not")]
        keep_tools: bool,
    },
    /// Modeled screw thread as a new body (ADR 0011): a threaded rod
    /// (external thread), or with `nut` a square nut (internal thread with
    /// radial clearance), axis along the normal of `plane` through `center`
    /// (plane coordinates). Stated 60° symmetric V test profile, one-turn
    /// lead-in/runout, `length` a whole number of pitches. **Faceted** with
    /// chord tolerance `chord_tol` (planar facets through points of the ideal
    /// helicoid; `rcad_kernel::threaded_rod` / `threaded_nut`). Parameters
    /// "diameter", "pitch", "length", and for a nut "nut_width",
    /// "clearance".
    Thread {
        plane: SketchPlane,
        #[serde(default)]
        center: [f64; 2],
        diameter: f64,
        pitch: f64,
        length: f64,
        #[serde(default, skip_serializing_if = "std::ops::Not::not")]
        left_hand: bool,
        chord_tol: f64,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        nut: Option<NutSpec>,
        body: BodyId,
    },
    /// Sheet-metal base face (format v7, `crate::sheet`): the closed
    /// profile of `sketch` as a plate `rule.thickness` thick along the sketch
    /// normal (against it with `flip`), new body `body`. `rule` is the sheet
    /// rule of every sheet feature of the body. Parameters "thickness",
    /// "radius", "k_factor", "relief_width", "relief_depth".
    SheetBase {
        sketch: FeatureId,
        rule: crate::sheet::SheetRule,
        #[serde(default, skip_serializing_if = "std::ops::Not::not")]
        flip: bool,
        body: BodyId,
    },
    /// Straight edge flange (format v7) on body `body` of sheet base
    /// `base`, along the base-profile line `edge` (sketch entity id): bend of
    /// `angle` rad (parameter `angle_deg`) toward the sketch normal (`down`:
    /// away from it), inside radius from the rule, straight `length` beyond
    /// the bend (tangent line to flange end), over the edge minus
    /// `start_offset`/`end_offset` (reliefs where it does not reach a corner).
    SheetFlange {
        base: FeatureId,
        body: BodyId,
        edge: u32,
        angle: f64,
        length: f64,
        #[serde(default, skip_serializing_if = "std::ops::Not::not")]
        down: bool,
        #[serde(default)]
        start_offset: f64,
        #[serde(default)]
        end_offset: f64,
    },
    /// Flat pattern of the sheet body of `base` (format v7) as the
    /// exact flat solid, new body `body` (a separate display state: the
    /// folded body is unchanged).
    SheetFlat { base: FeatureId, body: BodyId },
    /// Surface body (format v7): every SHELL_BASED_SURFACE_MODEL shell
    /// of an embedded STEP file as one open-shell body (no volume).
    ImportSurfaces {
        blob: BlobId,
        #[serde(default)]
        unit_override_to_mm: Option<f64>,
        body: BodyId,
    },
    /// Mesh repair (format v7; docs/MESH.md): a repaired copy of mesh
    /// body `source` as new body `body` (`rcad_exchange::mesh_repair`); the
    /// source is kept. Parameter "weld_tolerance".
    MeshRepair {
        source: BodyId,
        options: rcad_exchange::mesh_repair::RepairOptions,
        body: BodyId,
    },
    /// Mesh edit (format v8; docs/MESH.md): transform, plane cut or
    /// decimation of mesh body `source` (`rcad_exchange::mesh_edit`) as new
    /// body `body` (and `second_body`: the upper half of a two-sided cut);
    /// the source is kept. Parameters depend on the operation.
    MeshEdit {
        source: BodyId,
        op: rcad_exchange::mesh_edit::MeshEditOp,
        body: BodyId,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        second_body: Option<BodyId>,
    },
    /// Stitch (format v7) the faces of surface body `source` within
    /// healing `tolerance` mm into new body `body` (closed: a solid); the
    /// source body is kept. Parameter "tolerance".
    SurfaceStitch {
        source: BodyId,
        tolerance: f64,
        body: BodyId,
    },
    /// Fill every planar boundary loop of open-shell body `source` with a
    /// planar face (planarity within `tolerance`) as new body `body`
    /// (format v7). Parameter "tolerance".
    SurfaceFill {
        source: BodyId,
        tolerance: f64,
        body: BodyId,
    },
    /// Planar surface patch (format v7): the closed profile of
    /// `sketch` (holes allowed) as a one-face open surface body `body`.
    SurfacePatch { sketch: FeatureId, body: BodyId },
    /// Ruled surface (format v7): the closed profile, or else the
    /// open line chain, of `sketch` swept `distance` along the sketch normal
    /// (`reverse`: against it) as an open surface body. Parameter "distance".
    SurfaceExtrude {
        sketch: FeatureId,
        distance: f64,
        #[serde(default, skip_serializing_if = "std::ops::Not::not")]
        reverse: bool,
        body: BodyId,
    },
    /// Thicken (format v7) the single planar or cylindrical face of
    /// surface body `source` by `distance` mm along its normal (`reverse`:
    /// against it) into new solid body `body`. Parameter "distance".
    Thicken {
        source: BodyId,
        distance: f64,
        #[serde(default, skip_serializing_if = "std::ops::Not::not")]
        reverse: bool,
        body: BodyId,
    },
}

/// Nut of a [`FeatureKind::Thread`]: square `width`, radial `clearance` (mm).
